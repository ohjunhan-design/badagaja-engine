# -*- coding: utf-8 -*-
"""물때를 **따로** 셈합니다 — 검사만을 위한 독립 기준.

★ 왜 따로 만드나 (2026-09-26 바깥 검수 지적)

    처음에는 assets/js/tide.js 가 내어 준 셈을 검사가 그대로 썼습니다.
    「쓰는 셈과 재는 셈이 같아야 한다」고 생각했기 때문입니다.

    그런데 그러면 이렇게 됩니다.

        tide.js 가 계산한 값  ==  tide.js 가 계산한 값

    tide.js 자체가 틀려도 검사는 「맞습니다」라고 합니다.
    **검사가 아니라 메아리입니다.**

    그래서 이 파일은 tide.js 를 **한 줄도 안 봅니다.**
    파이썬으로, 다른 방식으로, 처음부터 다시 셉니다.
    둘이 어긋나면 어느 한쪽이 틀린 것이고, 그때 사람이 봅니다.

어떻게 다르게 셈하나
    tide.js   달·해의 황경을 각각 구해 위상각을 냅니다 (천문 계산)
    여기      **알려진 삭(그믐) 시각 표**를 바탕으로 셈합니다

    방식이 달라야 같은 실수를 두 번 하지 않습니다.

쓰는 법
    python engine/tide_reference.py               오늘부터 이레
    python engine/tide_reference.py 2026-09-26    그날부터 이레
"""
import sys
import datetime

# ── 알려진 삭(그믐) 시각 ────────────────────────────────────
# 한국천문연구원·미 해군천문대가 내는 값입니다. 한국시(KST) 기준.
# tide.js 의 천문 계산과 **아무 관계 없이** 여기 적어 둔 값만 씁니다.
# 표에 없는 날짜는 가장 가까운 삭에서 삭망월을 더해 셉니다.
삭시각 = [
    ('2026-01-19', 3), ('2026-02-17', 21), ('2026-03-19', 10),
    ('2026-04-17', 20), ('2026-05-17', 5), ('2026-06-15', 12),
    ('2026-07-14', 18), ('2026-08-13', 2), ('2026-09-11', 12),
    ('2026-10-11', 0), ('2026-11-09', 16), ('2026-12-09', 10),
    ('2027-01-08', 5), ('2027-02-07', 0), ('2027-03-08', 18),
]
삭망월 = 29.530588853      # 달이 같은 모양으로 돌아오는 주기(일)

# 7물때식 이름 — 국립해양조사원 스마트 조석예보 표기
# ★ 2026-09-30 — 1물의 이름이 「한물」이 아니라 **「한매」**입니다
#   국립해양조사원 스마트 조석예보의 「이름」 칸을 직접 받아 보니
#     음력 25일 한조금 · 26일 **한매**
#   였습니다. 우리 표는 26일(1물)을 「한물」이라 했습니다.
#   ★ 기준은 해양조사원입니다 (주인 지시 2026-09-26).
#   ★ tide_reference.py 도 **같은 표**를 들고 있어 둘이 똑같이
#     틀려 있었습니다. 베낀 표는 서로를 못 잡습니다 — 함께 고칩니다.
물때이름 = ['한매', '두메', '무릎사리', '배꼽사리', '가슴사리', '턱사리',
            '한사리', '목사리', '어깨사리', '허리사리', '한꺽기', '두꺽기',
            '선조금', '앉은조금', '한조금']
매이름 = ['두매', '세매', '네매', '다섯매', '여섯매', '일곱매', '여덟매',
          '아홉매', '열매', '한꺽기', '두꺽기', '아조', '조금', '무시', '한매']


def _삭목록():
    나옴 = []
    for 날, 시 in 삭시각:
        y, m, d = (int(x) for x in 날.split('-'))
        나옴.append(datetime.datetime(y, m, d, 시))
    return sorted(나옴)


def 음력날(날짜):
    """그 날이 음력 며칠인가.

    가장 가까운 앞선 삭을 찾아 며칠 지났는지 셉니다.
    삭이 든 날이 음력 1일입니다.
    """
    if isinstance(날짜, datetime.date) and not isinstance(날짜, datetime.datetime):
        날짜 = datetime.datetime(날짜.year, 날짜.month, 날짜.day)
    오늘0시 = datetime.datetime(날짜.year, 날짜.month, 날짜.day)

    삭들 = _삭목록()
    앞선삭 = None
    for 삭 in 삭들:
        삭0시 = datetime.datetime(삭.year, 삭.month, 삭.day)
        if 삭0시 <= 오늘0시:
            앞선삭 = 삭0시
        else:
            break
    if 앞선삭 is None:
        # 표보다 앞선 날 — 삭망월을 빼며 거슬러 올라갑니다
        첫삭 = datetime.datetime(삭들[0].year, 삭들[0].month, 삭들[0].day)
        지난날 = (첫삭 - 오늘0시).days
        돈바퀴 = int(지난날 / 삭망월) + 1
        앞선삭 = 첫삭 - datetime.timedelta(days=삭망월 * 돈바퀴)
        앞선삭 = datetime.datetime(앞선삭.year, 앞선삭.month, 앞선삭.day)
    elif 앞선삭 == datetime.datetime(삭들[-1].year, 삭들[-1].month, 삭들[-1].day):
        # 표보다 뒤 — 삭망월을 더하며 내려갑니다
        while True:
            다음 = 앞선삭 + datetime.timedelta(days=삭망월)
            다음 = datetime.datetime(다음.year, 다음.month, 다음.day)
            if 다음 > 오늘0시:
                break
            앞선삭 = 다음
    return (오늘0시 - 앞선삭).days + 1


def 물때번호(날짜):
    """음력날 → 물때 번호 (1~15).

    기준: 국립해양조사원 스마트 조석예보
      음력 16일 → 턱사리(6번째) · 17일 → 한사리(7번째)
    """
    m = (음력날(날짜) + 5) % 15
    return 15 if m == 0 else m


def 물때(날짜):
    n = 물때번호(날짜)
    return {'음력날': 음력날(날짜), '번호': n,
            '이름': 물때이름[n - 1], '매': 매이름[n - 1]}


def main():
    if len(sys.argv) > 1 and '-' in sys.argv[1]:
        y, m, d = (int(x) for x in sys.argv[1].split('-'))
        시작 = datetime.date(y, m, d)
    else:
        시작 = datetime.date.today()

    print('물때 — 독립 기준 (engine/tide_reference.py)')
    print('  tide.js 를 한 줄도 안 보고 따로 셈한 값입니다')
    print('')
    print('  날짜         음력   물때      매식')
    for i in range(7):
        날 = 시작 + datetime.timedelta(days=i)
        x = 물때(날)
        print('  %s %3d일 %-7s %s'
              % (날.isoformat(), x['음력날'], x['이름'], x['매']))
    return 0


if __name__ == '__main__':
    sys.exit(main())
