"""채비 하나를 가리키는 **한 곳**입니다 (2026-10-08).

★ 왜 생겼나 — 주인이 잡으셨습니다

    「**새로운 채비사진이 있는데 왜 구형을 사용하려는거야?**」

  `data/img/rig/` 에 새 채비 사진 32장(16종 × PC·모바일)이 있고
  `/rig/` 16쪽은 그것을 제대로 씁니다. 그런데 **어종 쪽 18개는
  하나도 안 쓰고** `art.채비도` 의 옛 SVG 를 그리고 있었습니다.
  `img/rig` 를 가리키는 어종 쪽은 **0개**였습니다.

  저는 그것을 못 보고, 어종 쪽끼리만 견주어 「같은 생성기에서
  나오니 구버전 혼용 0」이라 결론냈습니다. 그러고는 **구버전
  SVG 의 글자 겹침을 정성껏 고치고** 있었습니다.

★ 바깥 검수가 정한 길

    「/fish/ = 이 어종에 **어떤 채비를 쓰는지 빠르게 판단**
      /rig/  = 그 채비를 **실제로 어떻게 구성하는지 자세히 학습**」
    「같은 사진 파일을 **참조**하는 것은 괜찮습니다. 금지한 것은
      `fish용 복사본` · `rig용 원본` 처럼 **같은 자산을 두 벌로**
      유지하는 것이었습니다」
    「가장 좋은 구조는 **`rig_id` 하나로 통일**하는 겁니다.
      공통 함수가 rig_id → PC 그림 → 모바일 그림 → 상세 주소 →
      이름 을 모두 정하게 하세요. 그러면 fish 와 rig 가 서로
      다른 파일을 가리킬 여지가 크게 줄어듭니다」

  그래서 이 파일이 **그 한 곳**입니다. 어종 쪽도 채비 쪽도
  여기서만 자산을 받습니다. 두 곳에서 따로 지으면 반드시
  어긋납니다 (기억 「숫자는 한 곳에서만」).
"""
import os

여기 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# 사진이 사는 자리 — **`data/img/rig/`** 입니다.
#   `site/img/rig/` 가 아닙니다. 그곳은 빌드가 쪽을 다 만든 **뒤에**
#   채우는 생성물이라, 깨끗한 체크아웃(깃허브)에서는 비어 있습니다.
#   2026-10-06 에 그것 때문에 「사진 0장」이 나와 배포가 두 번 막혔습니다.
사진밭 = os.path.join(여기, 'data', 'img', 'rig')


def 있나(rig_id):
    """그 채비의 **사진이 저장소에 정말 있는가** (PC·모바일 둘 다)."""
    if not rig_id:
        return False
    return (os.path.isfile(os.path.join(사진밭, '%s.webp' % rig_id))
            and os.path.isfile(os.path.join(사진밭, '%s-m.webp' % rig_id)))


def 채비(rig_id, 채비자료):
    """`rig_id` 하나에서 **쓸 것을 모두** 냅니다.

    돌려주는 것 — 없으면 None
        {'id', '이름', '왜', '대상', '미끼',
         'PC사진', '모바일사진', '상세'}

    ★ 값을 지어내지 않습니다. 자료에 없으면 그 칸을 비웁니다.
      사진이 하나라도 없으면 **아예 None** 입니다 — 반쪽짜리
      카드를 만들지 않습니다.
    """
    if not rig_id or not 있나(rig_id):
        return None
    것 = ((채비자료 or {}).get('채비') or {}).get(rig_id)
    if not 것:
        return None
    return {
        'id': rig_id,
        '이름': 것.get('이름') or rig_id,
        '왜': 것.get('왜') or '',
        '대상': 것.get('대상') or '',
        '미끼': 것.get('미끼') or '',
        # 상대 경로입니다. 쪽마다 자리가 달라 `url.rel` 로 맞춥니다.
        'PC사진': 'img/rig/%s.webp' % rig_id,
        '모바일사진': 'img/rig/%s-m.webp' % rig_id,
        '상세': 'rig/%s.html' % rig_id,
    }


def 어종의채비(어종):
    """그 어종이 쓰는 `rig_id`.

    ★ 자료의 `그림` 칸이 곧 채비 갈래입니다 — 이름이 `rigs.json`
      의 열쇠, `data/img/rig/` 의 파일 이름과 **그대로 같습니다**
      (bottom · float · sabiki · egi · jighead …).
      새로 짓지 않고 있는 것을 씁니다.

    ★ 어종과 채비는 **1대1이 아닙니다** (바깥 검수)
      「어종 18개에 채비 16종이라고 해서 1:1일 필요는 없습니다.
        여러 어종이 같은 원투·다운샷·전유동찌를 공유하는 게
        정상입니다. 어종 → 채비는 N:1 로 두세요」
      실제로 원투 하나를 어종 여섯이 함께 씁니다.
    """
    if not isinstance(어종, dict):
        return None
    return 어종.get('그림') or None


def 첫줄(글, 최대=70):
    """긴 설명에서 **첫 문장 하나**만. 카드에는 짧게 적습니다.

    ★ 어종 쪽은 「어떤 채비를 쓰는지 **빠르게 판단**」하는 자리라
      긴 글을 통째로 옮기지 않습니다. 자세한 것은 `/rig/` 가 맡습니다.
    """
    글 = (글 or '').strip()
    if not 글:
        return ''
    for 끝 in ('. ', '다. ', '다\n'):
        i = 글.find(끝)
        if 0 < i <= 최대 + 10:
            return 글[:i + len(끝)].strip()
    if len(글) <= 최대:
        return 글
    자른것 = 글[:최대]
    빈칸 = 자른것.rfind(' ')
    return (자른것[:빈칸] if 빈칸 > 30 else 자른것).rstrip(' ·,') + '…'
