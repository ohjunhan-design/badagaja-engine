# -*- coding: utf-8 -*-
"""**한국 시각**을 한 곳에서 정합니다 (2026-10-14).

★ 왜 만들었나 — 하마터면 새벽마다 물때가 멈출 뻔했습니다

  제가 서버 PHP 에 `strtotime(date('Y-m-d'))` 로 「오늘」을
  정했습니다. 그런데 PHP 의 `date()` 는 **서버 기본 시간대**를
  따릅니다. 그 서버가 UTC 였다면 **한국 00~09시 아홉 시간 동안**
  「오늘」이 어제가 되어, 검증이 전부 「날이 섞였다」로 떨어지고
  **갱신이 통째로 멈췄을** 것입니다. 감독실이 코드를 읽다
  찾아냈습니다.

  같은 함정이 **제 파이썬 도구 여덟 자리**에도 있었습니다.
  `datetime.now()` 는 **그 컴퓨터의 시간대**를 따릅니다.
  제 윈도는 한국 시간이라 괜찮았지만, **판정은 깃허브
  우분투(UTC)에서 돕니다.** 거기서 돌면 한국 새벽에
  「운영 57곳이 전부 막힌다」는 **거짓 보고**가 나옵니다.

  제 기억에 「TZ= 를 붙이지 않기 — 윈도는 이미 KST」라고
  적어 두었는데 **반쪽만 맞았습니다.** 윈도에서는 맞고
  우분투에서는 틀립니다. 그래서 **어느 컴퓨터에서든 같도록
  시간대를 못 박습니다.**

★ 쓰는 법
      from engine.kst import 오늘, 오늘키, 지금
      오늘()     datetime.date   — 한국 날짜
      오늘키()   '10/14'         — 물때 자료의 날짜 키
      지금()     datetime        — 한국 시각 (시간대 붙음)

★ 물때 날짜를 다루는 곳은 **반드시 이것을 씁니다.**
  `datetime.now()` · `date.today()` 를 직접 쓰면 도는 컴퓨터에
  따라 답이 갈립니다. `engine/check_clock.py` 가 봅니다.
"""
import datetime

#: 한국 표준시. 서머타임이 없어 늘 +9 입니다.
KST = datetime.timezone(datetime.timedelta(hours=9))


def 지금():
    """한국 시각 (시간대가 붙은 datetime)."""
    return datetime.datetime.now(KST)


def 오늘():
    """한국 날짜 (date)."""
    return 지금().date()


def 오늘키(그날=None):
    """물때 자료의 날짜 키 — `10/14` 꼴.

    ★ 자료에 **연도가 없습니다.** 60일은 한 해를 넘지 못하므로
      같은 키가 두 번 나올 수 없어 이대로 충분합니다.
    """
    d = 그날 or 오늘()
    return '%d/%d' % (d.month, d.day)
