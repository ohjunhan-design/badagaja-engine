def 돌리기(도구, 인자=(), 시간=3600):
    """검사기를 돌려 (끝난값, 글) 을 돌려줍니다.

    ★ 돌리다 넘어지면 **NOT_TESTED** 입니다. PASS 가 아닙니다.
    """
    길 = os.path.join(ROOT, 도구.replace('/', os.sep))
    if not os.path.exists(길):
        길 = os.path.join(ROOT, 'engine', 도구)
    if not os.path.exists(길):
        return None, '도구가 없습니다: %s' % 도구
    환경 = dict(os.environ)
    환경['PYTHONIOENCODING'] = 'utf-8'
    # ★ 고리를 끊습니다 (2026-09-27)
    #   gate 가 3번으로 test_not_tested 를 돌리는데, 그 시험은
    #   gate 가 검산을 내는지 보려고 **gate 를 다시 돌립니다.**
    #   그 안에서 또 3번을 돌리니 끝이 없습니다.
    #   이 표시가 있으면 그 시험이 gate 를 다시 안 돌립니다.
    환경['BADAGAJA_GATE'] = '1'
    try:
        r = subprocess.run([sys.executable, 길] + list(인자),
                           capture_output=True, text=True, encoding='utf-8',
                           env=환경, timeout=시간)
    except subprocess.TimeoutExpired:
        글 = '시간이 넘었습니다 (%d초)' % 시간
        기록남기기(도구, 인자, None, 글)
        return None, 글
    except OSError as e:
        글 = '못 돌렸습니다: %s' % e
        기록남기기(도구, 인자, None, 글)
        return None, 글
    글 = (r.stdout or '') + (r.stderr or '')
    기록남기기(도구, 인자, r.returncode, 글)
    return r.returncode, 글


