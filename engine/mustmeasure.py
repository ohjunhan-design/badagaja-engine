import sys

# 끝난값 계약 — 통과 0 · 어김 1 · 안올림 3 · **못잼 4**
못잼 = 4


class 못쟀음(Exception):
    """검사를 수행할 수 없습니다. 통과가 아닙니다."""


def 있어야한다(것들, 무엇='볼 것', 최소=1, 어디=None, 터뜨릴까=False):
    """볼 것이 없으면 **못잼(4)으로 멈춥니다.**

    `터뜨릴까=True` 면 끝내지 않고 `못쟀음` 을 던집니다 —
    시험에서 쓰려고 둡니다.
    """
    수 = len(것들) if hasattr(것들, '__len__') else sum(1 for _ in 것들)
    if 수 >= 최소:
        return 수

    말 = ['',
          '  ✗ %s을(를) %d개밖에 못 모았습니다 (적어도 %d개는 있어야 합니다).'
          % (무엇, 수, 최소),
          '    **검사를 수행하지 못했습니다 — 통과가 아닙니다.**',
          '    0개면 돌 고리가 없어 어김도 안 나옵니다. 그것을',
          '    「탈이 없다」로 세면 검사기가 죽은 줄도 모릅니다.']
    if 어디:
        말.append('    본 곳 — %s' % 어디)
    말.append('    (끝난값 계약 — 통과 0 · 어김 1 · 안올림 3 · 못잼 %d)'
              % 못잼)
    글 = '\n'.join(말)
    if 터뜨릴까:
        raise 못쟀음(글)
    print(글)
    sys.exit(못잼)


def 꾸러미가있어야한다(이름, 왜='', 깔이름=None):
    """그 꾸러미가 없으면 **못잼(4)으로 멈춥니다.**

    ★ `setup-python` 은 깨끗한 파이썬을 깝니다 — 내 컴퓨터에 있는
      꾸러미가 거기엔 없습니다 (기억 「깨끗한 파이썬엔 꾸러미가 없습니다」).
    """
    try:
        __import__(이름)
    except ImportError:
        print('')
        print('  ✗ `%s` 가 없어 **한 줄도 못 봤습니다.**' % 이름)
        if 왜:
            print('    %s' % 왜)
        print('    이것은 통과가 아닙니다 — `pip install %s` 하세요.' % (깔이름 or 이름))
        print('    (일꾼 설정 넷에 깔기 단계가 들어 있습니다)')
        sys.exit(못잼)
