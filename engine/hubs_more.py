def 물때쪽(d, 언어='ko'):
    """물때표는 **권역 쪽에서만** 그립니다.

    여기는 「어느 바다 물때를 볼까」를 고르는 갈림길입니다.
    같은 표를 두 곳에서 그리면 한 곳을 고치고 다른 곳을 잊습니다.
    """
    쪽길 = 'tide/index.html' if 언어 == 'ko' else '%s/tide/index.html' % 언어
    묶음표 = d.색인['묶음이름']

    칸들 = []
    for 묶 in d.색인['묶음차례']:
        것들 = [r for r in d.권역들 if r['묶음'] == 묶]
        if not 것들:
            continue
        묶이름 = 묶음표[묶].get(언어) or 묶음표[묶]['ko']
        줄 = []
        for r in sorted(것들, key=lambda x: x.get('차례') or 0):
            관 = (r.get('물때관측소') or {}).get('이름') or ''
            줄.append(
                '<li><a href="%s"><b>%s</b>%s</a></li>'
                % (esc(url.rel(쪽길, url.region(r['id'], 언어))),
                   esc(_권역이름(r, 언어)),
                   ('<span>%s 관측소</span>' % esc(관)) if 관 else ''))
        칸들.append(칸(
            str(묶이름), '%d곳' % len(것들),
            '<ul class="hub-list hub-list--grid">%s</ul>' % ''.join(줄),
            흰=(len(칸들) % 2 == 0)))

    값 = _바탕값(
        d, 쪽길, 언어,
        제목='전국 물때표 — 57권역 만조·간조 시각 | %s'
             % d.사이트['이름']['ko'],
        짧은제목='전국 물때표',
        설명='전국 57개 바다 권역의 물때를 봅니다. 권역을 고르면 '
             '그날 만조·간조 시각과 물높이를 함께 보여 줍니다.',
        머리말='전국 물때',
        큰제목='어느 바다 물때를 보시겠어요',
        소개글='권역을 고르면 그날 만조·간조 시각과 물높이를 봅니다. '
               '물때는 같은 바다라도 관측소에 따라 조금씩 다릅니다. '
               '권역마다 가장 가까운 관측소를 기준으로 합니다.',
        한줄='57권역',
        갈래칸=''.join(칸들),
        꼬리안내='물때는 바람과 기압에 따라 예보와 달라질 수 있습니다. '
                 '갯바위에서는 물이 드는 시각보다 일찍 나오세요.',
        이름표글='57권역')
    return 쪽길, template.그리기('rig-parts.html', 값)


