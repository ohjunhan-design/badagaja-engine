def 물때쪽(d, 언어='ko'):
    """물때표는 **권역 쪽에서만** 그립니다.

    여기는 「어느 바다 물때를 볼까」를 고르는 갈림길입니다.
    같은 표를 두 곳에서 그리면 한 곳을 고치고 다른 곳을 잊습니다.
    """
    쪽길 = url.tide_list(언어)
    묶음표 = d.색인['묶음이름']

    칸들 = []
    for 묶 in d.색인['묶음차례']:
        것들 = [r for r in d.권역들 if r['묶음'] == 묶]
        if not 것들:
            continue
        묶이름 = 묶음표[묶].get(언어) or 묶음표[묶]['ko']
        줄 = []
        for r in sorted(것들, key=lambda x: x.get('차례') or 0):
            관 = (r.get('물때관측소') or {}).get('이름') or ''
            줄.append(
                '<li><a href="%s"><b>%s</b>%s</a></li>'
                % (esc(url.rel(쪽길, url.region(r['id'], 언어))),
                   esc(_권역이름(r, 언어)),
                   ('<span>%s 관측소 기준</span>' % esc(관)) if 관 else ''))
        칸들.append(칸(
            str(묶이름), '%d곳' % len(것들),
            '<ul class="hub-list hub-list--grid">%s</ul>' % ''.join(줄),
            흰=(len(칸들) % 2 == 0)))

    # ★ **지도를 되살립니다** (2026-10-02 주인이 먼저 찾으셨습니다)
    #   「언제 물때 페이지에 지도가 들어갈까?」
    #
    #   옛 사이트에는 있었습니다 — oldsite/js/tide-map.js (2026-09-23
    #   주인 지시). 새 쪽을 짜며 빠뜨린 것입니다. 끊긴 쪽 아홉과
    #   같은 모양입니다.
    #
    #   지피티 — 「옛 동작을 되살리되, 현재 지도 UI 규칙에 맞춰 다시
    #     입힙니다. 처음부터 새로 짜지 않습니다. 57개 카드를 처음부터
