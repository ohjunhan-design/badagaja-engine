"""검사 — **저희끼리 보는 말이 공개 쪽에 나가지 않았는가** (2026-10-01).

★ 왜 만드나 — 실제로 샜습니다
  `sources.html` 을 갱신 대장에서 지었더니, 대장에 적힌 저희 메모가
  그대로 쪽에 나왔습니다.

      「사람이 눈으로 확인 (클로드)」
      「직접 그림 (옛 저장소 tools/lesson-steps.ps1)」
      「옛 사이트 index.html 의 지도 (주인이 여섯 번 고쳐 만든 것)」

  주인 규칙 11 — **근거 자료(출처 주소·조사 메모)는 웹에 내지
  않습니다.** 자료에서 쪽을 짓는 것은 옳지만, 자료에는 저희끼리
  알아볼 말이 섞여 있습니다. **자료를 그대로 내보내면 샙니다.**

★ 규칙 26 — 「새 검사는 잡은 뒤에 만듭니다」
  고치는 데서 끝내면 다음에 또 샙니다. 자료가 늘 때마다 같은 일이
  생기므로 **검사가 지켜야** 합니다.

★ 막음입니다. 한 번이라도 새면 배포를 멈춥니다.
"""
import os
import re
import sys

여기 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# ★ **시험이 주는 사본을 봅니다** (2026-10-02 판정 [2])
#   전에는 `os.path.join(여기, 'site')` 로 **늘 진짜 site/ 만**
#   봤습니다. 검사기 자기검증이 사본을 만들어 일부러 깨뜨린 뒤
#   `BADAGAJA_SITE` 로 가리켜 주는데, 이 검사기는 그것을 안 보고
#   멀쩡한 진짜 쪽을 재고 「아무 탈 없다」고 했습니다.
#   그래서 **「검사기가 못 잡는다」로 두 가지가 헛되이 실패**하고
#   있었습니다. 다른 검사기들은 모두 환경값을 봅니다.
쪽밭 = os.environ.get('BADAGAJA_SITE', os.path.join(여기, 'site'))
sys.path.insert(0, 여기)
from engine import mustmeasure   # noqa: E402

# ── 공개 쪽에 **있으면 안 되는 말** ──────────────────
#   ① 저희를 가리키는 말 — 사이트는 주인이 운영하는 것입니다
#   ② 파일 이름·경로 — 어떻게 만드는지는 손님이 알 바 아닙니다
#   ③ 조사 메모 자리 — data-private 는 애초에 내보내지 않습니다
새면안되는것 = [
    ('클로드', '만드는 사람 이름 — 사이트는 주인이 운영합니다'),
    ('ChatGPT', '바깥 도구 이름'),
    ('지피티', '바깥 도구 이름'),
    ('data-private', '조사 자료 폴더 이름 (주인 규칙 11)'),
    ('두번째도전', '작업 폴더 이름'),
    ('옛 저장소', '저희끼리 쓰는 말'),
    ('tools/', '만드는 쪽 경로'),
    ('engine/', '만드는 쪽 경로'),
    ('build.py', '만드는 쪽 파일'),
    ('.ps1', '만드는 쪽 파일'),
    # ★ 「주인」만으로는 **정상 글을 잡습니다** (2026-10-01 첫 판에서 겪음)
    #     「양식장과 마을어장의 굴은 **주인이** 있으니 손대지 마세요」
    #     「바다에 떠 있는 칸마다 **주인이** 있습니다」
    #   둘 다 옳은 글입니다. 사이트 주인을 가리키는 말만 잡습니다.
    ('주인 지시', '저희끼리 쓰는 말'),
    ('주인 규칙', '저희끼리 쓰는 말'),
    ('주인이 정한', '저희끼리 쓰는 말'),
    ('주인이 여섯', '저희끼리 쓰는 말'),
    ('바깥 검수', '저희끼리 쓰는 말'),
]

# ★ **써도 되는 자리** — 거짓 경보를 막습니다
#   · <script> 안의 파일 이름은 쪽이 돌아가는 데 필요합니다
#   · 주소(href·src)의 경로는 쪽을 잇는 것입니다
_버릴칸 = re.compile(
    r'<(script|style)\b[^>]*>.*?</\1>|<!--.*?-->|'
    r'(href|src|content)="[^"]*"', re.S | re.I)


# ── 검사 등급 (계약-21) ──────────────────────────────
#   막는 것과 알리는 것을 **따로 모읍니다.** 한 덩이로 두면
#   나중에 「이건 알림만」 하고 싶을 때 검사기를 통째로
#   고쳐야 합니다.
막음, 알림 = [], []


def 보이는글(html):
    """손님 눈에 보이는 글만. 스크립트·주소는 뺍니다."""
    몸 = _버릴칸.sub(' ', html)
    return 몸


def 보기():
    샌것 = []
    # ★ 쪽을 하나도 못 읽어도 **「샌 것 없음」으로 통과**했습니다
    #   (2026-10-08 실측 — 바깥 검수 fail-open 전수조사)
    본쪽 = 0
    for 뿌리, _, 파일들 in os.walk(쪽밭):
        for 이름 in 파일들:
            if not 이름.endswith('.html'):
                continue
            # ★ 다른 검사기가 쓰는 **임시 파일**은 건너뜁니다
            #   (2026-10-01 — 판정이 도는 중에 `__재기임시.html` 이
            #    만들어졌다 지워지는 사이에 걸려 검사가 죽었습니다)
            if 이름.startswith('__'):
                continue
            길 = os.path.join(뿌리, 이름)
            상대 = os.path.relpath(길, 쪽밭).replace('\\', '/')
            try:
                글 = 보이는글(open(길, encoding='utf-8').read())
            except OSError:
                continue          # 읽는 사이에 사라졌으면 넘어갑니다
            본쪽 += 1
            for 말, 까닭 in 새면안되는것:
                자리 = 글.find(말)
                if 자리 < 0:
                    continue
                앞뒤 = re.sub(r'\s+', ' ',
                              글[max(0, 자리 - 50):자리 + len(말) + 50])
                샌것.append((상대, 말, 까닭, 앞뒤.strip()))
    mustmeasure.있어야한다(range(본쪽), '읽은 쪽', 최소=50, 어디=쪽밭)
    return 샌것


def main():
    # ★ 등급을 **둘로 나눕니다** (계약-21)
    #   막는 것과 알리는 것을 한 덩이로 두면, 나중에 「이건 알림만」
    #   하고 싶을 때 검사기를 통째로 고쳐야 합니다.
    for 것 in 보기():
        막음.append(것)          # 저희 메모가 새면 **무조건 막습니다**
    if 알림:
        print('[알림] 살펴볼 것 %d가지' % len(알림))
    if 막음:
        pass
    샌것 = 막음
    if not 샌것:
        print('[통과] 공개 쪽에 저희끼리 쓰는 말이 없습니다.')
        return 0
    print('[막음] 저희끼리 쓰는 말이 공개 쪽에 나갔습니다 — %d곳'
          % len(샌것))
    print('  주인 규칙 11 — 근거 자료·조사 메모는 웹에 내지 않습니다.')
    본것 = set()
    for 쪽, 말, 까닭, 앞뒤 in 샌것:
        열쇠 = (말, 앞뒤[:40])
        if 열쇠 in 본것:
            continue
        본것.add(열쇠)
        print()
        print('  %s' % 쪽)
        print('    「%s」 — %s' % (말, 까닭))
        print('    … %s …' % 앞뒤)
    print()
    print('  고칠 곳은 **쪽이 아니라 쪽을 짓는 자리**입니다.')
    print('  자료에는 저희끼리 알아볼 말을 적되, 쪽에는 손님이')
    print('  알아야 할 것만 내보내세요 (engine/hubs_site.py 의')
    print('  `_공개출처()` 가 그렇게 합니다).')
    return 1


if __name__ == '__main__':
    sys.exit(main())
