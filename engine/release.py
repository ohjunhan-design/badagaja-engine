"""두 **판**을 견줍니다 — 되돌릴 때 무엇을 지우고 무엇을 되돌릴지.

★ 왜 필요한가 (2026-10-08 주인 물음에서 시작)

  주인 — 「파일질라를 사용하면 더 빨라질까? 배포에 시간이 너무 많이
  걸려 백업본도 이 컴퓨터에 저장하면 훨씬 빠르잖아」

  재 보니 성공한 배포 #24 가 39분 26초였고 그 가운데
      서버 내려받기 10분 39초 + 되돌림 계획 재 보기 8분 54초
      = 19분 33초(**절반**)가 「되돌리기 준비」였습니다.
  올리는 것은 5분 9초뿐이라 파일질라로 바꿔도 3분밖에 못 줄입니다.

★ 바깥 검수가 정한 길

      「8분54초 제거는 가능하지만, 지금의 `/www 전체를 --delete
        rollback` 구조를 그대로 둔 채 그냥 빼면 안 됩니다 …
        **전체 서버 rollback → 배포 소유 파일만 rollback** 전환이
        필요합니다」

      배포 소유 파일 = build.json 의 926개 목록
        → 지난 성공 판으로 되돌림
      이번 판에만 생긴 파일 = 새 목록 − 옛 목록
        → **이것만** 지움
      api/ · zh-cn/ · 서버에만 있는 것
        → 되돌리기가 **건드리지 않음**

  그러면 지울 것이 **셈으로 정해져** 서버를 다시 훑을 까닭이
  없어집니다. 그리고 서버를 손으로 고쳤을 때 **오히려 더
  안전합니다** — 손으로 넣은 `api/foo.json` 은 되돌리기 대상이
  아니라 안 지웁니다.

★ 이 모듈은 **셈만** 합니다. 지우거나 올리지 않습니다.
  그래야 시험에서 진짜 서버 없이 재 볼 수 있습니다.
"""
import json


def 판읽기(글):
    """`build.json` 글에서 `{파일길: 지문}` 과 판 번호를 꺼냅니다.

    못 읽으면 `(None, None)` — **빈 목록과 다릅니다.**
    빈 목록은 「파일이 없다」이고 None 은 「모른다」입니다.
    그 둘을 섞으면 「아무것도 안 올린 판」으로 보고 **전부
    지우려 들 수 있습니다.**
    """
    if not 글:
        return None, None
    try:
        d = json.loads(글)
    except Exception:
        return None, None
    파일 = d.get('파일')
    if not isinstance(파일, dict):
        return None, None
    return 파일, d.get('판번호') or d.get('커밋짧은') or ''


def 견주기(옛파일, 새파일):
    """두 판을 견줍니다.

    돌려주는 것 — `{'생김': [...], '사라짐': [...], '바뀜': [...],
                    '그대로': [...]}` (모두 차례가 정해진 목록)

    ★ 차례를 정해 둡니다. 안 그러면 같은 자료로 두 번 돌릴 때
      결과가 달라져 「자료를 안 고쳤으면 결과가 같아야 한다」가
      깨집니다 (규칙 26).
    """
    옛 = 옛파일 or {}
    새 = 새파일 or {}
    생김 = sorted(k for k in 새 if k not in 옛)
    사라짐 = sorted(k for k in 옛 if k not in 새)
    바뀜 = sorted(k for k in 새 if k in 옛 and 새[k] != 옛[k])
    그대로 = sorted(k for k in 새 if k in 옛 and 새[k] == 옛[k])
    return {'생김': 생김, '사라짐': 사라짐,
            '바뀜': 바뀜, '그대로': 그대로}


# ★ 되돌리기가 **절대 건드리면 안 되는 것** (주인 규칙)
#   api/ 는 두 사이트가 함께 씁니다. 중국어판은 옛 자산입니다.
#   .htaccess 는 한 글자만 틀려도 사이트가 500 으로 멈춥니다.
건드리면안될것 = ('.htaccess', 'api/', 'zh-cn/', '.well-known/',
                  'favicon.ico')


def 건드리면안되나(길, 안될것=건드리면안될것):
    g = (길 or '').lstrip('/')
    for t in 안될것:
        if t.endswith('/'):
            if g.startswith(t):
                return True
        elif g == t or g.endswith('/' + t):
            return True
    return False


def 되돌림계획(옛파일, 새파일, 안될것=건드리면안될것):
    """이번 판(새)을 지난 판(옛)으로 되돌리는 계획.

    돌려주는 것 — `{'지울것': [...], '되돌릴것': [...], '막힘': 사유}`

    · 지울것   — 이번 판에만 생긴 파일. **이것만** 지웁니다.
    · 되돌릴것 — 바뀌었거나 사라진 파일. 지난 판 것으로 덮습니다.
    · 막힘     — 계획을 세울 수 없는 까닭. None 이면 괜찮습니다.

    ★ **서버 전체를 보지 않습니다.** 그래서 서버에만 있는 파일은
      손대지 않고, 되돌리기가 8분 54초짜리 재스캔 없이 끝납니다.
    """
    if 옛파일 is None or 새파일 is None:
        # ★ 모르면 **아무것도 지우지 않습니다.**
        #   빈 목록으로 셈하면 「전부 지워라」가 나옵니다.
        return {'지울것': [], '되돌릴것': [],
                '막힘': '지난 판이나 이번 판의 목록을 못 읽었습니다'}
    d = 견주기(옛파일, 새파일)
    지울것 = [k for k in d['생김'] if not 건드리면안되나(k, 안될것)]
    되돌릴것 = [k for k in (d['바뀜'] + d['사라짐'])
                 if not 건드리면안되나(k, 안될것)]
    return {'지울것': 지울것, '되돌릴것': sorted(되돌릴것), '막힘': None}


def 위험한가(계획, 모두=None, 몫한계=0.5):
    """지우려는 것이 지나치게 많으면 멈춥니다.

    한 판에서 절반 넘게 사라지는 일은 **정상이 아닙니다.** 목록을
    잘못 읽었거나 빈 판을 올렸을 때 그런 수가 나옵니다.
    """
    지울것 = 계획.get('지울것') or []
    if 계획.get('막힘'):
        return 계획['막힘']
    위험 = [k for k in 지울것 if 건드리면안되나(k)]
    if 위험:
        return '건드리면 안 될 것이 지울 목록에 있습니다: %s' % 위험[:3]
    if 모두 and len(지울것) > max(10, int(모두 * 몫한계)):
        return ('지울 것이 %d개로 너무 많습니다 (판 전체 %d개)'
                % (len(지울것), 모두))
    return None
