def _굵게(글):
    """자료의 `**…**` 를 굵게. **별표가 글자로 보이면 안 됩니다.**"""
    쪽 = esc(글 or '').split('**')
    나옴 = []
    for i, x in enumerate(쪽):
        나옴.append(('<b>%s</b>' % x) if i % 2 else x)
    return ''.join(나옴)


def _칩들(것):
    """★ **7단계 칩** — 맨 위에서 **차례를 한눈에** (2026-10-07 바깥 검수).

    「상단을 『왕초보 7단계 코스』로 만들고 7단계 네비칩을 둔다」
    「최상단 2~3화면 안에서 사용자가 이 페이지가 무엇을 주는지
      완전히 이해해야 합니다」

    칩은 쪽 안쪽 자리로 갑니다 — 보고 고르면 그 단계로 내려갑니다.
    """
    것들 = []
    for i, 단 in enumerate(것['단계'], 1):
        # ★ 칩에는 **짧은 이름**만 둡니다. 제목을 통째로 넣으면
        #   일곱 칸이 글자로 꽉 차 차례가 안 보입니다.
        #
        #   ★ **첫 낱말을 떼면 뜻이 끊깁니다** (2026-10-07 — 찍어 보고 알았습니다)
        #     「입질이 오면 짧게 챔질」 → 「입질이」
        #     「큰 고기는 뜰채로」     → 「큰」
        #     「떠날 때는 …」          → 「떠날」
        #   그래서 자료에 `짧은이름` 을 둡니다. 제목에서 **고른 말**이고
        #   지어낸 말이 아닙니다. 없으면 첫 낱말로 물러섭니다.
        이름 = (단.get('짧은이름')
                or (단.get('제목') or '').replace(',', ' ').split(' ')[0])
        것들.append('<a class="bc-chip" href="#bc-%d">'
                    '<i>%d</i><span>%s</span></a>'
                    % (i, i, esc(이름)))
    return ('<nav class="bc-chips" aria-label="단계 차례">%s</nav>'
            % ''.join(것들))


def _잔걸음(단):
    """③매듭·④던지기의 **잔걸음 미니도해**.

    「③ 매듭·④ 던지기는 **순서형 미니도해 강조**」(바깥 검수)

    ★ **자료에 적힌 것만** 그립니다. 없으면 빈 글자입니다 —
      짐작해서 단계를 만들지 않습니다. 잔걸음은 본문 글에 이미
      있던 말을 `lessons.json` 으로 옮겨 둔 것입니다.
    """
    것 = 단.get('잔걸음') or []
    if not 것:
        return ''
    칸들 = ''.join('<li class="bc-mini"><i>%d</i><b>%s</b></li>'
                   % (i, esc(x)) for i, x in enumerate(것, 1))
    return '<ol class="bc-minis">%s</ol>' % 칸들


def _강의칸(것):
    """★ **그림이 주인공인 큰 카드** (2026-10-07 바깥 검수 콘티).

    전에는 그림 일곱을 작은 격자(`.ls-grid`)에 담았습니다. 자료를
    재 보니 쪽 30,949자 가운데 **대부분이 그림(SVG)** 이고 글은
    단계마다 100자 안팎입니다. 즉 **글이 길어서** 답답한 것이
    아니라 **그림이 작아서** 읽을 것만 많아 보였습니다.

      「제일 중요한 건 지금 7장 그림을 **작게 장식처럼 넣지 말고,
        페이지의 주인공으로 크게** 쓰는 것입니다. 이 페이지는
        **글보다 그림이 앞에 와야** 합니다」

    그래서 한 단계가 한 칸을 차지합니다 — **그림 60~70% · 글 30~40%**.
    PC 는 짝수 칸마다 좌우를 바꿔(`is-reverse`) 눈이 지그재그로
    따라가고, 휴대폰은 **그림 위 · 글 아래로 고정**합니다
    (바깥 검수 — 「모바일은 교차배치 금지」).
    """
    칸들 = []
    for i, 단 in enumerate(것['단계'], 1):
        뒤집 = ' is-reverse' if i % 2 == 0 else ''
        칸들.append(
            '<article class="bc-lesson%s" id="bc-%d">\n'
            '<figure class="bc-visual">\n'
            '<svg viewBox="0 0 320 220" role="img" aria-label="%s 그림"'
            ' xmlns="http://www.w3.org/2000/svg">\n%s\n</svg>\n'
            '</figure>\n'
            '<div class="bc-copy">\n'
            '<i class="bc-no">%d</i>\n'
            '<h3 class="bc-title">%s</h3>\n'
            '<p class="bc-body">%s</p>\n%s</div>\n</article>'
            % (뒤집, i, esc(단.get('제목')), 단.get('그림') or '',
               i, esc(단.get('제목')), _굵게(단.get('글')),
               _잔걸음(단)))
    return ('<p class="bc-lede">%s</p>%s<div class="bc-lessons">%s</div>'
            % (_굵게(것.get('소개')), _칩들(것), ''.join(칸들)))


def _기초자료(d, 갈래):
    from engine import io as _io
    길 = os.path.join(여기, 'data', 'raw', 'lessons.json')
    것 = (_io.read_json(길, default={}).get('기초') or {}).get(갈래)
    return 것 if (것 and 것.get('단계')) else None


def 기초쪽(d, 갈래, 언어='ko'):
    """`갈래` 는 '낚시' 또는 '해루질'."""
    것 = _기초자료(d, 갈래)
    if not 것:
        return None
    낚시 = (갈래 == '낚시')
    쪽길 = url.basics(갈래, 언어)

    칸들 = [칸(것['제목'], 것.get('꼬리말') or '그림 강의',
               _강의칸(것), 흰=False)]

    # ── ★ **이제 어디로 갈까요** — 다음 행동 세 장 (2026-10-07)
    #
    #   전에는 여기서 **어종 여덟을 깔았습니다.** 기초를 막 본
    #   사람에게 고를 것을 여덟 개 주면 고르지 못합니다. 바깥
    #   검수 콘티가 셋으로 줄이라고 했습니다 —
    #
    #     「다음 행동을 고르는 **3장 카드**로 끝내는 게 좋습니다.
    #       어종 고르기 / 채비 묶는 법 / 오늘 물때」
    #
    #   「둘러보기」 같은 **모호한 이름은 뺍니다.** 손님은
    #   「둘러보기」보다 「어종 찾기·채비 보기·오늘 물때 보기」를
    #   훨씬 잘 알아봅니다.
    셀것 = len(d.안내(갈래) or [])
    갈곳 = [
        ('어종 고르기',
         url.guide_list(갈래, 언어),
         '%d가지 %s별 채비와 미끼'
         % (셀것, '어종' if 낚시 else '대상')),
        ('채비 묶는 법',
         url.rig_parts(언어),
         '그림으로 보는 채비 부품과 매듭'),
        ('오늘 물때',
         url.tide_list(언어),
         '가기 좋은 시간을 먼저 확인'),
    ]
    칸들.append(칸(
        '이제 어디로 갈까요', '다음 차례',
        '<div class="bc-next">%s</div>'
        % ''.join(
            '<a class="bc-next-card" href="%s">'
            '<strong>%s</strong><span>%s</span></a>'
            % (esc(url.rel(쪽길, 주)), esc(이), esc(설명))
            for 이, 주, 설명 in 갈곳)))

    # ── 나가기 전에 — **떠나기 직전 체크**로 자리를 옮겼습니다
    더볼것 = [
        ('오늘 물때 보기', url.tide_list(언어),
         '언제 나가야 하는지부터 정합니다'),
        ('금어기와 크기 제한', url.rule(언어),
         '잡아도 되는 것인지 먼저 봅니다'),
        ('무엇을 챙겨 가나', url.gear(언어) if 낚시 else url.catch_gear(언어),
         '장화·장갑·구명조끼부터'),
    ]
    칸들.append(칸(
        '나가기 전에', '이것만',
        '<div class="grid">%s</div>'
        % ''.join(
            '<a class="card card--go" href="%s">'
            '<h3 class="card-name">%s</h3>'
            '<p class="card-body">%s</p></a>'
            % (esc(url.rel(쪽길, 주)), esc(이), esc(설명))
            for 이, 주, 설명 in 더볼것),
        흰=False))

    무엇 = '바다낚시' if 낚시 else '해루질'
    값 = _바탕값(
        d, 쪽길, 언어,
        제목='%s 처음이라면 — 그림 %d장으로 배우는 기초 | %s'
             % (무엇, len(것['단계']), d.사이트['이름']['ko']),
        짧은제목='%s 처음이라면' % 무엇,
        설명=('낚싯대 이름부터 매듭·던지기·챔질까지, 어떤 물고기를 '
              '노리든 똑같은 기초만 그림 %d장에 모았습니다.'
              if 낚시 else
              '물때 보는 법부터 옷차림·안전·해감까지, 무엇을 잡든 '
              '똑같은 기초만 그림 %d장에 모았습니다.')
             % len(것['단계']),
        머리말='%s 기초' % 무엇,
        큰제목='왕초보 %s 기초' % 무엇,
        소개글=('어종마다 채비는 달라도 낚싯대 다루는 법은 모두 '
               '같습니다.' if 낚시 else
               '무엇을 잡든 물때와 안전이 먼저입니다.'),
        한줄='그림 %d장 · 번호 순서대로' % len(것['단계']),
        갈래칸=''.join(칸들),
        꼬리안내=('처음에는 못 잡는 것이 당연합니다. 자리와 물때를 '
                 '익히는 것이 먼저입니다.' if 낚시 else
                 '갯벌은 물이 빨리 들어옵니다. 물때표를 먼저 '
                 '보고 움직이세요.'),
        이름표글='그림 %d장' % len(것['단계']),
        _og갈래=('fish' if 낚시 else 'catch'))
    # ★ 겉틀이 body 클래스로 쓰는 값 — 안 주면 틀이 멈춥니다
    값.setdefault('쪽갈래', '')
    return 쪽길, template.그리기('rig-parts.html', 값)
