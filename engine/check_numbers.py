# -*- coding: utf-8 -*-
"""검사 — **쪽에 적힌 숫자가 자료와 맞는가** (2026-10-01).

★ 왜 만드나 — 「낚시 자리 **0곳**」이 쪽에 나갔습니다

  소개 쪽에 규모를 큰 숫자로 세우면서 이렇게 셌습니다 —

      낚시 = sum(d.셈(r, '낚시') for r in d.색인['권역'])

  그 열쇠가 권역 id 목록이 아니어서 **합이 0** 이 되었습니다.
  쪽에는 「갯바위·방파제 낚시 자리 **0곳**」이라고 찍혔습니다.

  검사기 34가지가 모두 통과했습니다. 아무도 **숫자가 말이 되는가**를
  보지 않았기 때문입니다. 글 속에 묻혀 있었으면 못 봤을 텐데,
  마침 큰 글씨로 세운 덕에 눈에 띄었습니다. **운이 좋았습니다.**

★ 주인 규칙 29 — 「사이트에 적는 숫자는 손으로 적지 않습니다. 자료에서
  셉니다」. 자료에서 세는 것만으로는 모자랍니다. **세는 방법이 틀릴
  수 있습니다.** 그래서 나온 값이 자료와 맞는지 다시 봅니다.

★ 무엇을 보나
  ① **0 이 적힌 자리** — 셈이 틀렸거나 자료가 비었다는 뜻입니다.
     진짜 0 이면 「없습니다」라고 글로 적지, 「0곳」이라 쓰지 않습니다.
  ② 쪽에 적힌 **포인트 수가 자료의 전체 수와 맞는가**
  ③ 묶음(낚시+해루질)의 합이 전체와 맞는가

★ 막음입니다. 틀린 숫자는 **사이트 전체의 신뢰를 깎습니다.**
"""
import os
import re
import sys

여기 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, 여기)
쪽밭 = os.environ.get('BADAGAJA_SITE') or os.path.join(여기, 'site')

from engine.data import 자료   # noqa: E402

# ★ 「0곳」이 나오면 안 되는 말들 — 숫자 뒤에 오는 단위
_영 = re.compile(r'<b>\s*0\s*</b>\s*<span>\s*(낚시 자리|해루질터|권역|사진)')
_영글 = re.compile(r'(낚시 자리|해루질터|포인트|해루질 자리)\s*<b>?0</b>?\s*곳')


# ── 검사 등급 (계약-21) ──────────────────────────────
#   막는 것과 알리는 것을 **따로 모읍니다.** 한 덩이로 두면
#   나중에 「이건 알림만」 하고 싶을 때 검사기를 통째로
#   고쳐야 합니다.
막음, 알림 = [], []


def 쪽들():
    for 뿌리, _, 파일들 in os.walk(쪽밭):
        for 이름 in 파일들:
            if not 이름.endswith('.html'):
                continue
            # ★ 다른 검사기가 쓰는 **임시 파일**은 건너뜁니다
            #   (2026-10-01 — 판정이 도는 중에 `__재기임시.html` 이
            #    만들어졌다 지워지는 사이에 걸려 검사가 죽었습니다)
            if 이름.startswith('__'):
                continue
            길 = os.path.join(뿌리, 이름)
            try:
                글 = open(길, encoding='utf-8').read()
            except OSError:
                continue          # 읽는 사이에 사라졌으면 넘어갑니다
            yield (os.path.relpath(길, 쪽밭).replace('\\', '/'), 글)


def main():
    d = 자료()
    전체 = d.셈()
    낚시, 해루질 = d.셈(갈래='낚시'), d.셈(갈래='해루질')
    권역수 = len(d.권역들)

    print('[1] 자료가 스스로 맞는가')
    if 낚시 + 해루질 != 전체:
        막음.append('낚시 %d + 해루질 %d ≠ 전체 %d'
                    % (낚시, 해루질, 전체))
        print('  ✗ 낚시 %d + 해루질 %d = %d · 전체는 %d'
              % (낚시, 해루질, 낚시 + 해루질, 전체))
    else:
        print('  · 낚시 %s + 해루질 %s = 전체 %s곳'
              % (format(낚시, ','), format(해루질, ','),
                 format(전체, ',')))
    if not (권역수 and 낚시 and 해루질):
        막음.append('자료에서 센 값에 0 이 있습니다')
        print('  ✗ 권역 %d · 낚시 %d · 해루질 %d — 0 이 있습니다'
              % (권역수, 낚시, 해루질))
    print('')

    print('[2] 쪽에 「0곳」이 적혀 있지 않은가')
    영쪽 = []
    for 쪽, 글 in 쪽들():
        if _영.search(글) or _영글.search(글):
            영쪽.append(쪽)
    if 영쪽:
        막음.append('「0」이 적힌 쪽 %d개' % len(영쪽))
        print('  ✗ 「0」이 적힌 쪽 %d개' % len(영쪽))
        for 쪽 in 영쪽[:8]:
            print('      %s' % 쪽)
        print('      → 셈이 틀렸거나 자료가 비었습니다. 진짜 0 이면')
        print('        「없습니다」라고 글로 적습니다.')
    else:
        print('  · 「0곳」이라 적힌 쪽이 없습니다')
    print('')

    print('[3] 사진 수가 **실제로 있는 사진**과 맞는가')
    # ★ 배열 길이를 더하는 것으로는 모자랍니다 (2026-10-01 바깥 검수)
    #   「388 이 정말 중복 제거된, 이용허락 확인 후 **사이트에서
    #     사용하는** 사진 레코드인지 확인한 뒤 숫자를 노출하세요」
    #   세어 보니 10장은 파일이 없었습니다(검수에서 거른 것).
    #   쪽에 적힌 수와 실제 수가 다르면 **한 장이라도** 알립니다.
    from engine.hubs_site import 밝힌사진들
    진짜사진 = len(밝힌사진들())
    적힌것 = set()
    for 쪽, 글 in 쪽들():
        if 쪽 not in ('photos.html', 'about.html'):
            continue
        for m in re.finditer(r'<b>([\d,]+)</b>\s*<span>\s*사진|'
                             r'사진\s*([\d,]+)장', 글):
            값 = (m.group(1) or m.group(2) or '').replace(',', '')
            if 값.isdigit():
                적힌것.add(int(값))
    틀린수 = sorted(x for x in 적힌것 if x != 진짜사진)
    if 틀린수:
        막음.append('사진 수가 다릅니다 — 쪽 %s · 실제 %d'
                    % (틀린수, 진짜사진))
        print('  ✗ 쪽에 적힌 수 %s · 실제로 있는 사진 %d장'
              % (틀린수, 진짜사진))
        print('      → 자료의 배열 길이가 아니라 **파일이 있고 촬영자·')
        print('        이용허락이 있는 것**만 세야 합니다.')
    else:
        print('  · 쪽에 적힌 사진 수가 실제(%d장)와 같습니다' % 진짜사진)
    print('')

    print('[4] 쪽에 적힌 전체 수가 자료와 맞는가')
    바른말 = {format(전체, ','), str(전체)}
    틀린쪽 = []
    for 쪽, 글 in 쪽들():
        for m in re.finditer(r'자리\s*<b>([\d,]+)</b>\s*곳|'
                             r'포인트\s*([\d,]+)\s*곳 한눈에', 글):
            값 = (m.group(1) or m.group(2) or '').strip()
            if 값 and ',' in 값 and 값 not in 바른말:
                # 권역 쪽은 제 권역 수를 적으므로 전체와 달라도 됩니다.
                # 네 자리 이상(1,000 넘는 수)만 전국 수로 봅니다.
                if len(값.replace(',', '')) >= 4:
                    틀린쪽.append('%s — %s' % (쪽, 값))
    if 틀린쪽:
        알림.append('전국 수가 다르게 적힌 곳 %d개' % len(틀린쪽))
        print('  ~ 전국 수가 다르게 적힌 곳 %d개 (자료: %s)'
              % (len(틀린쪽), format(전체, ',')))
        for x in 틀린쪽[:5]:
            print('      %s' % x)
    else:
        print('  · 전국 수를 적은 곳이 모두 %s 입니다' % format(전체, ','))
    print('')

    if 알림:
        print('살펴볼 것 %d가지 (막지 않습니다)' % len(알림))
        for x in 알림:
            print('  ~ %s' % x)
        print('')
    if 막음:
        print('손볼 곳 %d가지' % len(막음))
        for x in 막음:
            print('  ✗ %s' % x)
        print('')
        print('  ★ 숫자가 틀리면 **사이트 전체를 못 믿게 됩니다.**')
        print('    자료에서 세는 것만으로는 모자랍니다 —')
        print('    세는 방법이 틀릴 수 있습니다 (주인 규칙 29).')
        return 1
    print('쪽에 적힌 숫자가 자료와 맞습니다.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
