# -*- coding: utf-8 -*-
"""금어기·크기제한 **계산기**와 쪽 만들기.

★ 왜 따로 두나 (2026-10-01 합의 R-029)
  build.py 가 이미 4,713줄입니다. 규정은 **틀리면 사람이 법을
  어기는** 자료라 따로 두고, build 는 부르기만 합니다.

★ 상태를 자료에 저장하지 않습니다 (합의 R-003)
  「잡아도 됨」 같은 값을 자료에 적으면 날짜가 바뀌어도 그대로
  남습니다. **날짜·지역·어종을 받아 그때그때 셉니다.**

★ 「전국 금어기 없음」 ≠ 「잡아도 됨」 (합의 R-004)
  화면에 「잡아도 됩니다」라고 쓰지 않습니다. 금어기가 아니어도
  크기제한·지역 고시·마을 어장 규약이 있습니다.

★ 빈 칸을 「규정 없음」으로 보여 주지 않습니다 (합의 R-005)
  근거를 못 찾은 것은 **「확인 필요」**로 보여 줍니다.
  화면이 비면 보는 분은 「규정이 없구나」로 읽습니다.
"""
import io
import json
import os
import datetime

뿌리 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
자료길 = os.path.join(뿌리, 'data', 'raw', 'rules', '금어기.json')

# 상태 — 자료에 저장하지 않고 **셈합니다**
금지중 = '금지중'
크기만 = '크기제한'
지역규정 = '지역규정'
금어기없음 = '전국금어기없음'
확인필요 = '확인필요'

상태말 = {
    금지중: '지금 금어기입니다',
    크기만: '크기 제한이 있습니다',
    지역규정: '지역에 따라 다릅니다',
    금어기없음: '전국 기본 금어기에 해당하지 않습니다',
    확인필요: '규정 확인 중입니다',
}
상태색 = {
    금지중: 'bad',
    크기만: 'warn',
    지역규정: 'warn',
    금어기없음: 'ok',
    확인필요: 'na',
}


def 자료():
    if not os.path.isfile(자료길):
        return None
    return json.load(io.open(자료길, encoding='utf-8'))


def _날(s):
    """「05-11」 → (5, 11)."""
    a, b = s.split('-')
    return int(a), int(b)


def 기간안인가(기간, 날):
    """그 날이 금어기 안인가. **연말을 넘는 기간도 셉니다.**

    ★ 「12월 1일 ~ 다음 해 1월 31일」이 그렇습니다.
      시작이 끝보다 뒤면 해를 넘는 것입니다.
    """
    시작 = _날(기간['시작'])
    끝 = _날(기간['끝'])
    이날 = (날.month, 날.day)
    if 시작 <= 끝:
        return 시작 <= 이날 <= 끝
    return 이날 >= 시작 or 이날 <= 끝


def 상태(것, 날=None):
    """어종 하나의 **오늘 상태**를 셉니다.

    돌려주는 것 — (상태, 지금 걸린 금어기들, 크기제한들)
    """
    날 = 날 or datetime.date.today()
    걸린것 = [기 for 기 in 것.get('금어기간', [])
              if 기간안인가(기, 날)]
    크기들 = 것.get('크기제한', [])

    if 걸린것:
        # 전국이 걸렸으면 금지중, 지역만이면 지역규정
        if any(기['지역'].get('갈래') == '전국' for 기 in 걸린것):
            return 금지중, 걸린것, 크기들
        return 지역규정, 걸린것, 크기들
    if 것.get('금어기간') or 크기들:
        return (크기만 if 크기들 else 금어기없음), [], 크기들
    return 확인필요, [], []


def 크기글(크):
    """「각장 7cm 이하」 — **재는 법을 잃지 않습니다**."""
    값 = 크['값']
    값 = int(값) if float(값) == int(값) else 값
    재 = 크.get('재는법') or ''
    if 재 in ('전장', '무게', ''):
        재 = ''
    return ('%s %s%s 이하' % (재, 값, 크['단위'])).strip()


def 기간글(기):
    시작, 끝 = _날(기['시작']), _날(기['끝'])
    글 = '%d월 %d일 ~ %s%d월 %d일' % (
        시작[0], 시작[1],
        '다음 해 ' if 시작 > 끝 else '', 끝[0], 끝[1])
    곳 = 기['지역']
    if 곳.get('갈래') == '행정구역':
        글 = '%s %s' % (' · '.join(곳.get('포함', [])), 글)
    elif 곳.get('갈래') == '해역조건':
        글 = '%s — %s' % (곳.get('조건', ''), 글)
    return 글


def 오늘금지(d=None, 날=None):
    """오늘 금어기인 어종만 뽑습니다."""
    d = d or 자료()
    if not d:
        return []
    것들 = []
    for 것 in d['어종']:
        st, 걸린, _ = 상태(것, 날)
        if st in (금지중, 지역규정):
            것들.append((것, st, 걸린))
    return 것들


def 어종상태표(날=None):
    """어종 아이디 → 상태. 어종·해루질 쪽이 **같은 계산기**를 씁니다.

    ★ 합의 완료조건 5 — 어종 18쪽 + 해루질 17쪽이 같은 계산기를 씁니다.
      쪽마다 따로 세면 같은 물고기가 쪽마다 다른 말을 합니다.
    """
    d = 자료()
    표 = {}
    if not d:
        return 표
    for 것 in d['어종']:
        st, 걸린, 크기들 = 상태(것, 날)
        for i in (것.get('사이트어종') or []):
            표[i] = {
                '상태': st,
                '말': 상태말[st],
                '색': 상태색[st],
                '법령명': 것['법령명'],
                '학명': 것.get('학명'),
                '금어기간': [기간글(기) for 기 in 것.get('금어기간', [])],
                '지금걸림': [기간글(기) for 기 in 걸린],
                '크기제한': [크기글(크) for 크 in 크기들],
                '메모': [기.get('메모') for 기 in 것.get('금어기간', [])
                         if 기.get('메모')],
            }
    return 표
