def 지형갈래(지형):
    """해안형인가 · 예외형인가. 둘 다 아니면 (False, False)."""
    g = 지형 or ''
    예외 = any(t in g for t in 예외형)
    해안 = (not 예외) and any(t in g for t in 해안형)
    return 해안, 예외


