"""**사이트가 쓰는 숫자를 한 곳에서 셉니다** (2026-10-01).

★ 왜 — 공개판에서 숫자가 서로 달랐습니다
  바깥 검수가 실제 주소를 열어 보고 찾았습니다 —

      홈         57권역 · 3,603포인트 · 축제 197개      (맞음)
      guide/     70 제철 어종·패류 / 81 지역 축제       (다름)
      data.html  사진 **200장** · 축제 쪽 **191개**      (낡음)
                 한국어 369쪽 · 중국어 106쪽

  「About 숫자는 바로잡았지만 사이트 전체 숫자 **source-of-truth 는
    아직 하나가 아닙니다.** 단순 문자열 금지가 아니라 **의미가 같은
    통계끼리 같은 계산 함수를 쓰게** 해야 합니다」

  맞는 말입니다. 쪽마다 제 나름대로 세면 **반드시 갈립니다.**
  주인 규칙 29 — 「사이트에 적는 숫자는 손으로 적지 않습니다.
  자료에서 셉니다」. 그런데 **세는 자리가 여럿이면** 자료에서
  세어도 값이 달라집니다. 그래서 세는 **함수**를 하나로 모읍니다.

★ 쓰는 법
      from engine import counts
      수 = counts.모두(d)
      수['포인트']      3603
      수['사진']         378

★ 여기 없는 숫자를 쪽에 적지 않습니다.
  새 숫자가 필요하면 **여기에 더하고** 쪽은 읽기만 합니다.
"""
import os

여기 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _사진들():
    """**파일이 진짜 있고 촬영자·이용허락이 있는 사진.**

    자료가 두 갈래(photos.json · spot-photos-new.json)이고,
    그중 열 장은 검수에서 걸러 파일을 안 올렸습니다.
    배열 길이를 더하면 388 이 나오지만 실제는 378 입니다.
    """
    from engine.hubs_site import 밝힌사진들
    return 밝힌사진들()


def 모두(d):
    """쪽이 적는 모든 숫자. **이 표에 없는 수는 쪽에 적지 않습니다.**"""
    from engine import io as _io

    쪽밭 = os.environ.get('BADAGAJA_SITE') or os.path.join(여기, 'site')
    안내 = (d.안내('낚시') or []), (d.안내('해루질') or [])
    규정 = _io.read_json(
        os.path.join(여기, 'data', 'raw', 'rules', '금어기.json'),
        default={})

    # ★ **쪽 수는 세지 않습니다** (2026-10-01에 겪은 일)
    #   site/ 의 .html 을 세었더니 **만드는 차례에 따라 값이
    #   달라졌습니다** — data.html 을 만드는 시점에는 68쪽,
    #   다 만들면 446쪽. 계약-07(멱등성)을 어겼습니다.
    #   안내띠가 「파일이 있는지」로 정하던 것과 **같은 잘못**입니다.
    #
    #   손님에게 「446쪽」은 중요하지 않습니다. 「권역 57 ·
    #   포인트 3,603」이 중요합니다. 그래서 아예 뺍니다.
    #   꼭 필요해지면 **자료에서 셀 수 있는 식**으로 만듭니다.

    return {
        '권역': len(d.권역들),
        '묶음': len(d.색인['묶음차례']),
        '포인트': d.셈(),
        '낚시': d.셈(갈래='낚시'),
        '해루질': d.셈(갈래='해루질'),
        '낚시어종': len(안내[0]),
        '해루질대상': len(안내[1]),
        # ★ **「안내가 있는 것」과 「이름만 있는 것」은 다릅니다**
        #   (2026-10-01 바깥 검수가 공개판에서 찾아낸 불일치)
        #
        #     어종모두  35   **안내 쪽이 있는** 어종·대상
        #     어종이름  104  포인트에 적힌 **대상 어종 이름표**
        #
        #   첫 화면이 「제철 어종·해루질 **안내** 104」라고 적고
        #   `catch/` 로 보내고 있었습니다. 손님은 104개 안내를
        #   기대하는데 **35개뿐**입니다. 「안내」라고 썼으면
        #   안내가 있는 수를 적어야 합니다.
        #
        #   둘 다 옳은 숫자입니다. **이름이 달라야 합니다.**
        '어종모두': len(안내[0]) + len(안내[1]),
        '어종이름': len((d.어종 or {}).get('어종') or []),
        '축제': len(d.축제들),
        '규정종': len(규정.get('어종') or []),
        '사진': len(_사진들()),
    }


def 글(수, 열쇠):
    """세 자리마다 쉼표. **쪽에 적을 때는 늘 이것을 지납니다.**"""
    return format(수[열쇠], ',')
