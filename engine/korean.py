# -*- coding: utf-8 -*-
"""한글 다듬기 — 조사 고르기.

왜
    「바다가자닷컴이(가)」처럼 괄호를 쓰면 읽기 불편합니다.
    받침이 있는지 보고 알맞은 조사를 고릅니다.

    이름은 자료에서 오므로 어떤 글자로 끝날지 미리 알 수 없습니다.
    그래서 **기계가 골라야** 합니다.

쓰는 법
    조사('바다가자닷컴', '이') → '바다가자닷컴이'
    조사('태안', '은')         → '태안은'
    조사('여수', '로')         → '여수로'      (ㄹ 받침·모음은 '로')
"""
import re

# 앞: 받침 있을 때 · 뒤: 받침 없을 때
_짝 = {
    '이': ('이', '가'), '가': ('이', '가'),
    '은': ('은', '는'), '는': ('은', '는'),
    '을': ('을', '를'), '를': ('을', '를'),
    '과': ('과', '와'), '와': ('과', '와'),
    '아': ('아', '야'), '야': ('아', '야'),
    '으로': ('으로', '로'), '로': ('으로', '로'),
}

_한글 = re.compile(r'[가-힣]')
# 숫자·영문으로 끝날 때 읽는 소리의 받침 여부
_숫자받침 = {'0': True, '1': True, '3': True, '6': True, '7': True, '8': True,
             '2': False, '4': False, '5': False, '9': False}
_영문받침 = set('lmnrLMNR')   # 엘·엠·엔·알 은 받침으로 읽습니다


def 받침(말):
    """마지막 글자에 받침이 있나. 없으면 None (알 수 없음)"""
    말 = (말 or '').strip()
    말 = re.sub(r'[\s\)\]\}\'"·,]+$', '', 말)
    if not 말:
        return None
    끝 = 말[-1]
    if _한글.match(끝):
        return (ord(끝) - 0xAC00) % 28 != 0
    if 끝.isdigit():
        return _숫자받침.get(끝)
    if 끝.isalpha():
        return 끝 in _영문받침
    return None


def 조사(말, 조사글자):
    """말 뒤에 알맞은 조사를 붙여 돌려줍니다"""
    짝 = _짝.get(조사글자)
    if not 짝:
        return '%s%s' % (말, 조사글자)
    있음 = 받침(말)
    if 있음 is None:           # 알 수 없으면 괄호로 — 틀리게 쓰느니 낫습니다
        return '%s%s(%s)' % (말, 짝[0], 짝[1])
    # 'ㄹ' 받침은 '으로' 가 아니라 '로' 입니다
    if 조사글자 in ('로', '으로') and 있음:
        끝 = 말.strip()[-1]
        if _한글.match(끝) and (ord(끝) - 0xAC00) % 28 == 8:   # ㄹ
            return '%s로' % 말
    return '%s%s' % (말, 짝[0] if 있음 else 짝[1])
