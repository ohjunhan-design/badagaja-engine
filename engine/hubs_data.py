여기 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def 이름글(것, 언어='ko'):
    """자료의 `이름` 을 글로. **꾸러미일 수도 있습니다.**

    ★ 2026-10-01 — 권역은 `{'ko':…,'zh':…}`, 어종은 글자입니다.
      그냥 이으면 `dict` 가 섞여 터집니다. 같은 실수를 두 번 해서
      **꺼내는 자리를 하나로** 모았습니다 (계약-01).
    """
    값 = 것.get('이름')
    if isinstance(값, dict):
        return 값.get(언어) or 값.get('ko') or 것.get('id') or ''
    return 값 or 것.get('id') or ''


def 표(머리, 줄들):
    ths = ''.join('<th scope="col">%s</th>' % esc(h) for h in 머리)
    trs = []
    for 줄 in 줄들:
        칸들 = ['<th scope="row">%s</th>' % 줄[0]]
        칸들 += ['<td>%s</td>' % c for c in 줄[1:]]
        trs.append('<tr>%s</tr>' % ''.join(칸들))
    return ('<div class="rl-tablewrap"><table class="rl-table">'
            '<thead><tr>%s</tr></thead><tbody>%s</tbody></table></div>'
            % (ths, ''.join(trs)))


def 가진자료쪽(d, 언어='ko'):
    쪽길 = url.data(언어)
    수 = counts.모두(d)
    ㄱ = lambda k: counts.글(수, k)          # noqa: E731

    # ── 큰 숫자 넷 — **3초에 규모를 알립니다** (주인 규칙 6-1)
    큰수 = ('<div class="bignums">%s</div>' % ''.join(
        '<div class="bignum"><b>%s</b><span>%s</span></div>'
        % (esc(ㄱ(k)), esc(이름))
        for k, 이름 in (('권역', '바다 권역'),
                        ('포인트', '해루질·낚시 자리'),
                        ('어종모두', '제철 어종·대상'),
                        ('축제', '바다 축제'))))

    칸들 = []
    칸들.append(칸(
        '무엇을 가지고 있나', '한눈에',
        큰수
        + '<p class="long">바다가자닷컴이 모으고 정리한 자료를 한 쪽에 '
        '적었습니다. <b>숫자는 자료 파일에서 그대로 세었고</b>, 쪽을 '
        '다시 만들 때마다 갱신됩니다. 날마다 바뀌는 물때·날씨·축제 '
        '일정은 공공기관 자료를 그때그때 받아 보여 줍니다.</p>',
        흰=False))

    # ── 권역 — 묶음별로 **자료에서 셉니다**
    묶음줄 = []
    for 묶 in d.색인['묶음차례']:
        것들 = [r for r in d.권역들 if r['묶음'] == 묶]
        if not 것들:
            continue
        이름 = (d.색인['묶음이름'][묶].get(언어)
                or d.색인['묶음이름'][묶]['ko'])
        묶음줄.append((esc(이름), str(len(것들)),
                       esc(' · '.join(이름글(r, 언어) for r in 것들))))
    칸들.append(칸(
        '바다 권역 — %s개' % ㄱ('권역'), '1',
        표(['지역', '권역 수', '어디어디'], 묶음줄)
        + '<p class="long">권역 쪽 하나에 <b>오늘 물때 · 포인트 · 제철 · '
        '축제 · 먹거리 · 명소 · 코스</b>가 함께 있습니다.</p>'))

    칸들.append(칸(
        '물때 — %s권역 실시간' % ㄱ('권역'), '2',
        '<ul class="dots">'
        '<li><b>오늘 물때</b> — 1물~15물(7물때식)과 물 빠짐 정도</li>'
        '<li><b>간조·만조</b> — 시각과 물높이. 국립해양조사원 '
        '조석예보(가까운 관측소)</li>'
        '<li><b>2주 물때표</b>와 <b>이번 주 요일 추천</b> — 어느 날 '
        '많이 빠지는지</li>'
        '<li><b>시간별 물높이 그래프</b> — 오늘·내일·모레</li>'
        '<li><b>일출·일몰</b> — 권역 좌표로 계산</li></ul>'
        '<p class="pt-in"><a href="%s">전국 물때표</a> · '
        '<a href="%s">물때표 보는 법</a></p>'
        % (esc(url.rel(쪽길, url.tide_list(언어))),
           esc(url.rel(쪽길, url.muldae(언어)))),
        흰=False))

    # ── 포인트 — 출입·지형을 **세어서** 보입니다
    출입셈, 지형셈 = {}, {}
    for x in d.포인트들:
        출 = x.get('출입') or '자유'
        출입셈[출] = 출입셈.get(출, 0) + 1
        if x.get('지형'):
            지형셈[x['지형']] = 지형셈.get(x['지형'], 0) + 1
    포인트줄 = [
        ('전체', ㄱ('포인트') + '곳',
         '좌표 · 지형 · 대상 어종 · 시기 · 채비 · 가는 길'),
        ('낚시', ㄱ('낚시') + '곳', '갯바위 · 방파제 · 항구'),
        ('해루질', ㄱ('해루질') + '곳', '갯벌 · 물 빠진 바위'),
    ]
    막힌것 = sorted(((a, b) for a, b in 출입셈.items() if a != '자유'),
                    key=lambda t: -t[1])
    if 막힌것:
        from engine.build import 출입말
        포인트줄.append(
            ('들어갈 때 확인',
             format(sum(b for _a, b in 막힌것), ',') + '곳',
             esc(' · '.join('%s %s곳' % (출입말(a), format(b, ','))
                            for a, b in 막힌것[:4]))))
    칸들.append(칸(
        '해루질·낚시 자리 — %s곳' % ㄱ('포인트'), '3',
        표(['갈래', '수', '무엇이 있나'], 포인트줄)
        # ★ **한 문장 안에서 스스로 모순이었습니다** (2026-10-02 바깥 감사)
        #   「걸어서 닿는 자리만 싣고, 배로만 갈 수 있는 곳은 따로
        #    표시합니다」 — 걸어서 닿는 것만 싣는다면서 배로만 가는
        #   곳을 표시한다니 앞뒤가 안 맞습니다. 사실은 **싣습니다.**
        + ('<p class="long">근거는 <b>해양수산부 갯바위 낚시 포인트 '
           '공개자료</b>와 지자체·해경 고시, 그리고 두 곳 이상에서 '
           '확인한 조사 결과입니다. 배 위에서 하는 <b>선상낚시는 '
           '싣지 않습니다</b>. 섬·갯바위처럼 <b>배로 들어가 뭍에서 '
           '하는 자리</b>는 싣고, 자리마다 어떻게 들어가는지를 '
           '밝힙니다 — 배로만 들어가는 곳이 %s곳입니다.</p>'
           % format(d.출입셈('배로만'), ','))))

    # ── 어종
    낚 = d.안내('낚시') or []
    해 = d.안내('해루질') or []
    칸들.append(칸(
        '제철 어종·해루질 대상 — %s종' % ㄱ('어종모두'), '4',
        '<ul class="dots">'
        '<li><b>낚시 %s종</b> — %s</li>'
        '<li><b>해루질 %s종</b> — %s</li></ul>'
        '<p class="long">어종마다 <b>나오는 철 · 채비 · 미끼 · 손질법</b>과 '
        '그 어종이 나오는 포인트를 잇습니다. 잡는 차례는 그림으로 '
        '보입니다.</p>'
        '<p class="pt-in"><a href="%s">무엇을 잡나 전체 보기</a></p>'
        % (ㄱ('낚시어종'),
           esc(' · '.join(이름글(x, 언어) for x in 낚)),
           ㄱ('해루질대상'),
           esc(' · '.join(이름글(x, 언어) for x in 해)),
           esc(url.rel(쪽길, url.guide_hub(언어)))),
        흰=False))

    칸들.append(칸(
        '규정 — 금어기·금지체장 %s종' % ㄱ('규정종'), '5',
        '<p class="long">수산자원관리법 시행령 별표와 해양수산부 고시, '
        '시·도 고시를 자료로 두고 <b>오늘 날짜로 다시 셉니다.</b> '
        '쪽에 적힌 금어기는 손으로 쓴 것이 아니라 그날 계산한 것입니다.</p>'
        '<p class="notice">시·도지사 고시로 기간이 지역마다 다른 어종이 '
        '있고, 어업 방식에 따른 예외도 많습니다. <b>출조 전 관할 지자체 '
        '고시를 확인해 주세요.</b></p>'
        '<p class="pt-in"><a href="%s">금어기와 크기 제한 보기</a></p>'
        % esc(url.rel(쪽길, url.rule(언어)))))

    칸들.append(칸(
        '바다 축제 — %s개' % ㄱ('축제'), '6',
        '<p class="long">전국 %s개 권역의 바다 축제를 달과 지역으로 '
        '걸러 봅니다. 축제마다 <b>언제 · 어디서 · 무엇을 하나</b>와 '
        '가는 길, 가까운 바다를 함께 적습니다.</p>'
        '<p class="pt-in"><a href="%s">축제 달력 보기</a></p>'
        % (ㄱ('권역'), esc(url.rel(쪽길, url.festival_list(언어)))),
        흰=False))

    칸들.append(칸(
        '사진 — %s장' % ㄱ('사진'), '7',
        '<p class="long">공공기관이 공개한 사진과 자유 이용 허락(CC)이 '
        '붙은 사진만 씁니다. <b>파일이 실제로 올라가 있고 촬영자·이용허락을 '
        '확인한 것</b>만 셉니다.</p>'
        '<p class="pt-in"><a href="%s">사진 출처 보기</a></p>'
        % esc(url.rel(쪽길, url.photos(언어)))))

    칸들.append(칸(
        '쪽은 이렇게 이뤄집니다', '8',
        '<p class="long">권역 %s곳 · 묶음 %s곳 · 포인트 목록 · 어종 %s쪽 · '
        '채비 · 축제 %s쪽, 그리고 사이트를 밝히는 쪽(소개 · 자료 출처 · '
        '개인정보처리방침 · 사진 출처)으로 이뤄집니다.</p>'
        '<p class="long">이 숫자는 모두 <b>한 곳에서 세어</b> 여러 쪽에 '
        '나눠 적습니다. 쪽마다 따로 세면 반드시 어긋나기 때문입니다.</p>'
        % (ㄱ('권역'), ㄱ('묶음'), ㄱ('어종모두'), ㄱ('축제')),
        흰=False))

    값 = _바탕값(
        d, 쪽길, 언어,
        제목='바다가자닷컴이 가진 자료 — 권역 %s · 포인트 %s · 어종 %s · '
             '금어기 %s | %s'
             % (ㄱ('권역'), ㄱ('포인트'), ㄱ('어종모두'), ㄱ('규정종'),
                d.사이트['이름']['ko']),
        짧은제목='가진 자료',
        설명='전국 %s개 권역의 해루질·낚시 자리 %s곳, 제철 어종 %s종, '
             '금어기 %s종, 바다 축제 %s개를 한 쪽에 모았습니다.'
             % (ㄱ('권역'), ㄱ('포인트'), ㄱ('어종모두'), ㄱ('규정종'),
                ㄱ('축제')),
        머리말='가진 자료',
        큰제목='바다가자닷컴이 가진 자료',
        소개글='모으고 정리한 것을 한 쪽에 적었습니다.',
        한줄='권역 %s · 자리 %s곳 · 어종 %s종 · 축제 %s개'
             % (ㄱ('권역'), ㄱ('포인트'), ㄱ('어종모두'), ㄱ('축제')),
        갈래칸=''.join(칸들),
        꼬리안내='숫자는 쪽을 다시 만들 때마다 자료에서 새로 셉니다. '
                 '손으로 적지 않습니다.',
        이름표글='%s곳' % ㄱ('포인트'),
        _og갈래='guide')
    # ★ 겉틀이 body 클래스로 쓰는 값 — 안 주면 틀이 멈춥니다
    값.setdefault('쪽갈래', '')
    return 쪽길, template.그리기('rig-parts.html', 값)
