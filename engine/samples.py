# -*- coding: utf-8 -*-
"""검사 표본에 **반드시 들어야 하는 쪽**을 찾습니다 (2026-10-08).

★ 왜 이것이 필요한가

  새 짜임을 **한 쪽에만 켜 놓으면**(먼저 재어 보려고) 그 쪽이
  표본에 없어서 **아무 검사기도 안 봅니다.** 켠 줄도 모르고
  지나갑니다. 겪은 일 — 포인트 상세 패널을 여수 한 쪽에 켰는데,
  콘솔·휴대폰·광고 검사의 표본 포인트 쪽은 모두 태안이었습니다.
  (기억 「새 쪽은 검사 표본에도 — 표본에 없으면 영영 안 봅니다」)

★ 왜 **공용**으로 두는가

  표본을 고르는 검사기가 여럿입니다(console·mobile·ads …).
  각자에 손으로 넣으면 **한 곳을 빠뜨립니다.** 규칙 26 —
  「생성기가 여럿이라 한 곳을 빠뜨리기 쉬우니, 되도록 한 차례에
    후처리로 넣습니다」. 여기 한 곳만 고치면 모두 따라옵니다.

★ **쪽 이름을 박지 않습니다**

  「여수 쪽」이라 적어 두면 대표 쪽이 바뀔 때 조용히 깨집니다.
  (기억 「시험에 이름을 박지 않기」 · 「쪽 종류는 쪽이 말하게」)
  그 짜임을 켠 쪽은 **자기가 싣는 스크립트로 자신을 밝힙니다.**
  대표가 어디로 옮겨 가도 저절로 따라갑니다.
"""
import glob
import os
import re

from engine import io


# ── 「무엇으로 아는가」를 한곳에 적습니다
#
#   이름            쪽이 이 스크립트를 실으면 그 짜임을 켠 쪽입니다
특별한짜임 = (
    ('포인트상세패널', 'point-panel.js'),
)


def 켠쪽들(뿌리):
    """특별한 짜임을 켠 쪽을 짜임마다 **하나씩** 돌려줍니다.

    돌려주는 것 — `[(이름, 절대경로), …]`. 켠 쪽이 없으면 빈 목록
    입니다. **없는 것을 만들어 내지 않습니다.**
    """
    나옴 = []
    쪽길들 = sorted(glob.glob(os.path.join(뿌리, '**', '*.html'),
                              recursive=True))
    for 이름, 파일 in 특별한짜임:
        무늬 = re.compile(r'<script[^>]+src="[^"]*' + re.escape(파일))
        for 길 in 쪽길들:
            if 무늬.search(io.read(길, default='')):
                나옴.append((이름, 길))
                break
    return 나옴
