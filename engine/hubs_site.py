def _공개출처(글):
    """대장의 출처 메모를 **손님이 볼 말로** 다듬습니다."""
    글 = (글 or '').strip()
    if not 글:
        return '직접 정리'
    # 괄호 안은 저희 메모입니다 — 뗍니다
    import re as _re
    글 = _re.sub(r'\s*[(（][^)）]*[)）]', '', 글).strip()
    # ★ **공백이 있는 가운뎃점**으로만 쪼갭니다 (2026-10-01)
    #   그냥 `·` 로 쪼갰더니 「시·도 조례」가 「시 · 도 조례」로,
    #   「별표1·2」가 「별표1 · 2」로 **갈라졌습니다.**
    #   한국어에서 가운뎃점은 낱말을 **붙이는 데도** 씁니다.
    쪽 = [x.strip() for x in _re.split(r'\s+·\s+|\s*;\s*', 글) if x.strip()]
    남 = [x for x in 쪽 if not any(n in x for n in _내부낱말)]
    if not 남:
        return '직접 정리'
    return ' · '.join(남)


