import sys
import math
import datetime

라디안 = math.pi / 180.0


def _각(x):
    return math.sin(x * 라디안)


def 델타T(해):
    """지구가 도는 것이 고르지 않아 생기는 어긋남(초).

    천문 셈은 역학시(TD)로 나오고, 시계는 세계시(UT)입니다.
    2005~2050년에 쓰는 어림식입니다 (Espenak·Meeus).
    2026년에 75초쯤이라, 분 단위로 보는 우리에게는 넉넉합니다.
    """
    t = 해 - 2000.0
    return 62.92 + 0.32217 * t + 0.005589 * t * t


def 율리우스일_에서_날짜(jd):
    """율리우스일 → 파이썬 날짜시각 (UTC 기준)."""
    jd = jd + 0.5
    Z = int(jd)
    F = jd - Z
    if Z < 2299161:
        A = Z
    else:
        α = int((Z - 1867216.25) / 36524.25)
        A = Z + 1 + α - int(α / 4)
    B = A + 1524
    C = int((B - 122.1) / 365.25)
    D = int(365.25 * C)
    E = int((B - D) / 30.6001)
    날 = B - D - int(30.6001 * E) + F
    달 = E - 1 if E < 14 else E - 13
    해 = C - 4716 if 달 > 2 else C - 4715
    날정수 = int(날)
    남은 = (날 - 날정수) * 86400.0
    기본 = datetime.datetime(해, 달, 날정수)
    return 기본 + datetime.timedelta(seconds=남은)


def 삭(k):
    """k 번째 삭의 시각 (세계시 UT).

    k = 0 은 2000년 1월 6일의 삭입니다. 1 씩 늘면 다음 삭입니다.
    Meeus 49장 그대로입니다.
    """
    T = k / 1236.85
    T2 = T * T
    T3 = T2 * T
    T4 = T3 * T

    # 역학시 기준 어림 시각
    JDE = (2451550.09766 + 29.530588861 * k
           + 0.00015437 * T2 - 0.000000150 * T3 + 0.00000000073 * T4)

    E = 1 - 0.002516 * T - 0.0000074 * T2

    M = 2.5534 + 29.10535670 * k - 0.0000014 * T2 - 0.00000011 * T3
    Ms = (201.5643 + 385.81693528 * k + 0.0107582 * T2
          + 0.00001238 * T3 - 0.000000058 * T4)
    F = (160.7108 + 390.67050284 * k - 0.0016118 * T2
         - 0.00000227 * T3 + 0.000000011 * T4)
    Ω = 124.7746 - 1.56375588 * k + 0.0020672 * T2 + 0.00000215 * T3

    # 49장 표 49.A — 삭 보정 (25항)
    보정 = (
        -0.40720 * _각(Ms)
        + 0.17241 * E * _각(M)
        + 0.01608 * _각(2 * Ms)
        + 0.01039 * _각(2 * F)
        + 0.00739 * E * _각(Ms - M)
        - 0.00514 * E * _각(Ms + M)
        + 0.00208 * E * E * _각(2 * M)
        - 0.00111 * _각(Ms - 2 * F)
        - 0.00057 * _각(Ms + 2 * F)
        + 0.00056 * E * _각(2 * Ms + M)
        - 0.00042 * _각(3 * Ms)
        + 0.00042 * E * _각(M + 2 * F)
        + 0.00038 * E * _각(M - 2 * F)
        - 0.00024 * E * _각(2 * Ms - M)
        - 0.00017 * _각(Ω)
        - 0.00007 * _각(Ms + 2 * M)
        + 0.00004 * _각(2 * Ms - 2 * F)
        + 0.00004 * _각(3 * M)
        + 0.00003 * _각(Ms + M - 2 * F)
        + 0.00003 * _각(2 * Ms + 2 * F)
        - 0.00003 * _각(Ms + M + 2 * F)
        + 0.00003 * _각(Ms - M + 2 * F)
        - 0.00002 * _각(Ms - M - 2 * F)
        - 0.00002 * _각(3 * Ms + M)
        + 0.00002 * _각(4 * Ms)
    )

    # 행성 때문에 생기는 잔 보정 (14항)
    A = [
        (299.77 + 0.107408 * k - 0.009173 * T2, 0.000325),
        (251.88 + 0.016321 * k, 0.000165),
        (251.83 + 26.651886 * k, 0.000164),
        (349.42 + 36.412478 * k, 0.000126),
        (84.66 + 18.206239 * k, 0.000110),
        (141.74 + 53.303771 * k, 0.000062),
        (207.14 + 2.453732 * k, 0.000060),
        (154.84 + 7.306860 * k, 0.000056),
        (34.52 + 27.261239 * k, 0.000047),
        (207.19 + 0.121824 * k, 0.000042),
        (291.34 + 1.844379 * k, 0.000040),
        (161.72 + 24.198154 * k, 0.000037),
        (239.56 + 25.513099 * k, 0.000035),
        (331.55 + 3.592518 * k, 0.000023),
    ]
    보정 += sum(w * _각(a) for a, w in A)

    JDE += 보정
    때 = 율리우스일_에서_날짜(JDE)
    # 역학시 → 세계시
    return 때 - datetime.timedelta(seconds=델타T(때.year))


def 삭_한국시(k):
    """k 번째 삭의 시각 (한국시 KST = 세계시 + 9시간)."""
    return 삭(k) + datetime.timedelta(hours=9)


def k범위(첫해, 끝해):
    """그 해들을 덮는 k 의 범위."""
    # k 0 이 2000년이고 한 해에 열두 번 남짓입니다
    처음 = int((첫해 - 2000) * 12.3685) - 2
    마지막 = int((끝해 + 1 - 2000) * 12.3685) + 2
    return 처음, 마지막


def 삭목록(첫해, 끝해):
    """그 해들의 삭을 한국시로 모두 냅니다."""
    처음, 마지막 = k범위(첫해, 끝해)
    나옴 = []
    for k in range(처음, 마지막 + 1):
        t = 삭_한국시(k)
        if 첫해 <= t.year <= 끝해:
            나옴.append((k, t))
    return 나옴


def 음력날(날, 첫해=None, 끝해=None):
    """그 날이 음력 며칠인가 — 삭이 든 날이 1일입니다.

    tide.js 와 **다른 길**로 셉니다. 여기는 삭 그 순간을 바로 내고,
    그 삭이 든 **한국시 날짜**부터 며칠째인지만 셉니다.
    """
    if isinstance(날, datetime.datetime):
        날 = 날.date()
    처음, 마지막 = k범위(날.year - 1, 날.year + 1)
    앞선삭날 = None
    for k in range(처음, 마지막 + 1):
        t = 삭_한국시(k).date()
        if t <= 날:
            if 앞선삭날 is None or t > 앞선삭날:
                앞선삭날 = t
    if 앞선삭날 is None:
        return None
    return (날 - 앞선삭날).days + 1


def main():
    args = [x for x in sys.argv[1:] if not x.startswith('--')]
    올해 = datetime.date.today().year
    첫해 = int(args[0]) if args else 올해
    끝해 = int(args[1]) if len(args) > 1 else 첫해

    print('천문 기준 삭 시각 (Meeus 49장 · 한국시)')
    print('  이 파일은 assets/js/tide.js 를 한 줄도 보지 않습니다.')
    print('')
    목록 = 삭목록(첫해, 끝해)
    print('  %d~%d년 삭 %d회' % (첫해, 끝해, len(목록)))
    print('')
    보일것 = 목록 if len(목록) <= 30 else 목록[:15]
    for k, t in 보일것:
        위험 = ''
        if t.hour < 2 or t.hour >= 22:
            위험 = '  ← 자정 언저리 (하루가 갈릴 수 있습니다)'
        print('    k=%-5d %s%s' % (k, t.strftime('%Y-%m-%d %H:%M:%S'), 위험))
    if len(목록) > 30:
        print('    … 그 밖 %d회' % (len(목록) - 15))
    return 0


if __name__ == '__main__':
    sys.exit(main())
