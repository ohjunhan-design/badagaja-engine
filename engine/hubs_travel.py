import os

from engine import url
from engine import counts
from engine import template
from engine.hubs import esc, 칸, _바탕값

여기 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# ★ 세 갈래 — 바깥 검수가 글까지 정해 주었습니다
#
#   다만 세 번째는 **바꿨습니다.** 검수는 「머물 곳 — 바다 가까운
#   숙소 찾기」를 제안했는데, **숙소 자료가 없습니다.**
#   권역 자료(data/raw/travel/)에 있는 것은 이것뿐입니다 —
#       명소 393 · 먹거리 277 · 코스 171 · 마을 90
#   권역 쪽에도 숙소 칸이 없습니다(id="spot"·"eat"·"course").
#
#   **없는 것을 있는 척 보내면 안 됩니다.** 눌렀는데 숙소가
#   없으면 단추가 거짓말을 한 것입니다 — 검수가 (나)를 반대한
#   까닭과 같습니다(「단추의 약속과 도착지가 다릅니다」).
#   그래서 자료가 있는 **코스**로 바꿨습니다.
갈래들 = (
    ('볼거리', '바다 보고 어디를 더 둘러볼까요?', '명소', 'spot', '명소'),
    ('먹거리', '이 지역에서 무엇을 먹을까요?', '먹거리', 'eat', '먹거리'),
    ('어떻게 돌까', '하루를 어떻게 짤까요?', '코스', 'course', '코스'),
)


def 여행쪽(d, 언어='ko'):
    쪽길 = url.travel(언어)
    수 = counts.모두(d)

    # ── 세 갈래 고르기 — **첫 화면에서 바로**
    # ★ 갈래마다 **실제 수를 셉니다** (주인 규칙 29)
    #   「명소 393곳」처럼 보이면 눌러 볼 까닭이 생깁니다.
    def _셈(자료칸):
        n = 0
        for r in (d.여행들 or {}).values():   # 여행들 은 **꾸러미**입니다
            v = r.get(자료칸)
            if v:
                n += len(v) if hasattr(v, '__len__') else 1
        return n
    고르기 = ''.join(
        '<a class="card card--go" href="#%s">'
        '<h3 class="card-name">%s</h3>'
        '<p class="card-body">%s</p>'
        '<p class="pt-use">%s</p></a>'
        % (esc(아이디), esc(이름), esc(물음),
           esc('전국 %s곳' % format(_셈(자료칸), ',')))
        for 이름, 물음, _속, 아이디, 자료칸 in 갈래들)

    칸들 = [칸(
        '무엇을 즐길까요', '세 갈래',
        '<div class="grid">%s</div>' % 고르기
        + '<p class="long">바다에서 보낼 시간은 정했으니, 이제 '
        '<b>그 김에 무엇을 더 할지</b> 고릅니다. 고르시면 그 권역 '
        '쪽에서 실제로 무엇이 있는지 보여 드립니다.</p>',
        흰=False)]

    # ── 갈래마다 권역 고르기
    #    ★ 권역 차례는 **사이트가 쓰는 차례 그대로**입니다
    #      (주인이 정한 것 — 제주를 첫 번째로. 바깥 검수도
    #       「기존 사이트가 사용하는 고정 권역 순서를 그대로」)
    for 이름, 물음, 속, 아이디, _자료칸 in 갈래들:
        묶음칸 = []
        for 묶 in d.색인['묶음차례']:
            것들 = [r for r in d.권역들 if r['묶음'] == 묶]
            if not 것들:
                continue
            묶음이름 = (d.색인['묶음이름'][묶].get(언어)
                        or d.색인['묶음이름'][묶]['ko'])
            고리 = []
            for r in 것들:
                이름값 = r.get('이름')
                보일이름 = (이름값.get(언어) or 이름값.get('ko')
                            if isinstance(이름값, dict) else 이름값) or r['id']
                고리.append(
                    '<a href="%s#%s">%s</a>'
                    % (esc(url.rel(쪽길, url.region(r['id'], 언어))),
                       esc(아이디), esc(보일이름)))
            묶음칸.append(
                '<div class="tv-group"><h3 class="tv-g">%s</h3>'
                '<nav class="toc-chips">%s</nav></div>'
                % (esc(묶음이름), ''.join(고리)))
        칸들.append(
            '<section class="section section--%s" id="%s"><div class="wrap">'
            '<div class="section-head"><p class="kicker">%s</p>'
            '<h2 class="serif">%s</h2><p class="lead">%s</p></div>'
            '%s</div></section>'
            % ('white' if 아이디 == 'spot' else
               ('soft' if 아이디 == 'eat' else 'white'),
               esc(아이디), esc(속), esc(물음), esc('%s — 권역을 고르세요'
                                                   % 이름),
               ''.join(묶음칸)))

    값 = _바탕값(
        d, 쪽길, 언어,
        제목='바다 여행 — 볼거리·먹거리·코스 | %s'
             % d.사이트['이름']['ko'],
        짧은제목='바다 여행',
        설명='바다에 갔다가 무엇을 함께 즐길지 고릅니다. 전국 %s개 '
             '권역의 명소·지역 음식·바다 가까운 숙소로 이어집니다.'
             % counts.글(수, '권역'),
        머리말='바다 여행',
        큰제목='바다에 갔다가 무엇을 함께 즐길까',
        소개글='볼거리 · 먹거리 · 코스 가운데 고르고, 권역을 '
               '누르면 그곳에 실제로 무엇이 있는지 보여 드립니다.',
        한줄='전국 %s개 권역' % counts.글(수, '권역'),
        갈래칸=''.join(칸들),
        꼬리안내='영업시간·가격처럼 자주 바뀌는 것은 가시기 전에 '
                 '한 번 더 확인해 주세요.',
        이름표글='%s개 권역' % counts.글(수, '권역'),
        _og갈래='guide')
    return 쪽길, template.그리기('rig-parts.html', 값)
