def 글(x):
    return html.escape(str(x or ''), quote=False)


def 설명글(x):
    """그림 **설명**에 쓰는 글 — `**…**` 를 굵게 냅니다.

    ★ 2026-09-30 — 어종 쪽 그림 설명에 **별표가 그대로** 보였습니다.
      「이름 그대로 **돌에 사는 고기**라 암초대가 있어야 합니다」
      자료에 `**…**` 로 적으면 굵게 나오는 것이 이 틀의 약속인데
      (build.py 의 `_굵게()`), 그림 설명만 `글()` 이라 그랬습니다.
      figcaption 은 HTML 이므로 <b> 가 그대로 듣습니다.
    """
    return re.sub(r'\*\*(.+?)\*\*', r'<b>\g<1></b>', 글(x))


def 글자폭(글자, 크기):
    """글 한 줄의 대략 폭(px). 한글은 크기만큼, 그 밖은 절반쯤."""
    w = 0.0
    for c in 글자:
        if c in '*':
            continue                     # 굵게 표시는 안 보입니다
        w += 크기 * (1.0 if ord(c) > 0x2000 else 0.55)
    return w


def 여러줄(글자, x, y, 폭, 크기=12, 줄간=None, 색='#41606b',
           굵기=None, 가운데=False, 투명=None, 최대줄=4):
    """긴 글을 **칸 폭에 맞춰 나눠** SVG `<text>` 로 냅니다.

    ★ SVG `<text>` 는 저절로 줄바꿈이 안 됩니다 (2026-10-01).
      그냥 넣으면 viewBox 밖으로 뻗고, 휴대폰에서 쪽이 가로로
      넘칩니다. 여기 한 곳에서 나눕니다 (계약-01).

    ★ 굵게 표시가 줄 경계를 넘으면 줄마다 닫고 다시 엽니다.
    """
    글자 = (글자 or '').strip()
    if not 글자:
        return ''
    줄간 = 줄간 or 크기 + 4
    줄들, 이번 = [], ''
    for 낱말 in 글자.split(' '):
        뒤 = (이번 + ' ' + 낱말).strip()
        if 이번 and 글자폭(뒤, 크기) > 폭:
            줄들.append(이번)
            이번 = 낱말
            if len(줄들) >= 최대줄:
                break
        else:
            이번 = 뒤
    if 이번 and len(줄들) < 최대줄:
        줄들.append(이번)
    # 한 낱말이 칸보다 길면 글자 단위로 자릅니다 (한글은 띄어쓰기가
    # 드물어 낱말 하나가 길 수 있습니다)
    고친 = []
    for 한줄 in 줄들:
        while 글자폭(한줄, 크기) > 폭 and len(한줄) > 1:
            n = len(한줄)
            while n > 1 and 글자폭(한줄[:n], 크기) > 폭:
                n -= 1
            고친.append(한줄[:n])
            한줄 = 한줄[n:]
        고친.append(한줄)
    남김 = [t for t in 고친 if t]
    줄들 = 남김[:최대줄]
    # ★ **잘리면 말줄임표를 붙입니다** (2026-10-01)
    #   「따로 다는 것이」에서 끊겨 뜻이 거꾸로 읽혔습니다
    #   (원문은 「따로 다는 것이 **아닙니다**」). 전문은 옆
    #   부품 표에 있으니, 더 있다는 것만 알리면 됩니다.
    if len(남김) > 최대줄 and 줄들:
        줄들[-1] = 줄들[-1].rstrip() + '…'

    # ★ 굵게 표시가 줄을 넘으면 줄마다 닫고 엽니다
    열림 = False
    맞춘 = []
    for 한줄 in 줄들:
        if 열림:
            한줄 = '**' + 한줄
        열림 = (한줄.count('**') % 2 == 1)
        if 열림:
            한줄 = 한줄 + '**'
        맞춘.append(한줄)

    덧 = ''
    if 굵기:
        덧 += " font-weight='%d'" % 굵기
    if 가운데:
        덧 += " text-anchor='middle'"
    if 투명 is not None:
        덧 += " opacity='%s'" % 투명
    return ''.join(
        "<text x='%d' y='%d' font-size='%s' fill='%s'%s>%s</text>"
        % (x, y + i * 줄간, 크기, 색, 덧, 그림글(t))
        for i, t in enumerate(맞춘))


def 그림글(x):
    """그림(SVG) 안 글씨 — `**…**` 를 굵게 냅니다.

    ★ 2026-09-30 — 채비도 안 부품 귀띔에 **별표가 그대로** 보였습니다.
      「**위 고리에 에기, 아래 고리에 봉돌**을 끼웁니다」
      SVG 에서는 `<b>` 가 **안 듣습니다.** HTML 이 아니기 때문입니다.
      `<tspan font-weight='700'>` 을 씁니다.
    """
    return re.sub(r'\*\*(.+?)\*\*',
                  r"<tspan font-weight='700'>\g<1></tspan>", 글(x))


