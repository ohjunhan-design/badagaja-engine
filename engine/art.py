사진위에얹을까 = False


def 자리그림(어종, 쪽길=None):
    """어디에 서서 노리나 — **사진과 떨어진 일반 도해**입니다 (640×240).

    ★ 사진 위에 얹지 않습니다 (2026-10-08 주인 지시 — 위 주석).
      `사진위에얹을까` 를 켜면 옛 길로 돌아가지만, 그때는 **그
      사진의 그 자리**를 자료로 입증할 수 있어야 합니다.
    """
    이름 = 이름of(어종)
    어디 = 말of(어종, '어디서') or ''

    갈래 = ('하구' if '하구' in 어디 or '강' in 어디
            else '갯바위' if '갯바위' in 어디
            else '방파제')
    바탕 = (_예술자료().get('바탕') or {}).get(갈래) or {}
    사진 = 바탕.get('파일')

    if not (사진위에얹을까 and 쪽길 and _사진있나(사진)):
        return _자리그림_도형(어종)

    from engine import url
    주소 = url.rel(쪽길, 사진)
    물선 = float(바탕.get('물선y') or 150)
    # ★ **자르는 자리**도 자료에서 (2026-10-07 바깥 검수)
    #   640×240 은 2.67:1 이라 원본에서 띠 하나만 남습니다.
    #   어디를 남기느냐에 따라 「발밑」이 읽히기도 하고
    #   빈 물만 보이기도 합니다.
    자르기 = 바탕.get('자르기') or 'xMidYMid'

    # ── 어종마다 다른 표시 — **자료에서 읽습니다** (주인 지시)
    바닥 = _고르기(어디, '바닥')
    층 = _고르기(어디, '층')
    조류 = _고르기(어디, '조류')

    # ★ **서는 자리는 자료에서 읽습니다** (2026-10-07)
    #   사진마다 지형이 달라 한 좌표로 박으면 **물 위**에
    #   점이 찍힙니다. 실제로 그랬습니다.
    서x, 서y = [float(v) for v in (바탕.get('서는자리')
                                   or [196, 물선 - 16])]
    꾸밈 = [
        # 화살표 — 바깥 검수 「지금보다 굵게」
        "<path d='M%.0f %.0f l58 -34' stroke='%s' stroke-width='4'"
        " stroke-linecap='round'/>" % (서x, 서y - 8, 풀빛),
        "<circle cx='%.0f' cy='%.0f' r='11' fill='%s'"
        " stroke='#fff' stroke-width='3'/>" % (서x, 서y, 풀빛),
    ]

    # 노리는 쪽 — 주황 점선 곡선. 층이 있으면 그 깊이로 내립니다
    # ★ 노리는 곳도 자료에서 — 다만 **층**이 있으면 그만큼
    #   위아래로 옮깁니다 (어종마다 노리는 깊이가 다릅니다).
    노리x, 노리y = [float(v) for v in (바탕.get('노리는곳')
                                       or [430, 물선 + 40])]
    if 층:
        깊이 = float(층.get('y') or 0.45)
        노리y = 물선 + (236 - 물선) * 깊이
    꾸밈.append(
        "<path d='M%.0f %.0f Q%.0f %.0f %.0f %.0f' stroke='%s'"
        " stroke-width='4.2' fill='none' stroke-linecap='round'"
        " stroke-dasharray='9 7'/>"
        % (서x + 26, 서y + 12,
           (서x + 노리x) / 2, 서y + (노리y - 서y) * 0.92,
           노리x - 14, 노리y, 붉음))
    꾸밈.append(
        "<circle cx='%.0f' cy='%.0f' r='8' fill='%s'"
        " stroke='#fff' stroke-width='2.6'/>"
        % (노리x, 노리y, 붉음))

    # ── 라벨은 **2개까지**입니다 (바깥 검수)
    #    첫째는 늘 「서는 자리」, 둘째는 어종마다 다른 것 하나.
    라벨 = [_알약(서x, 서y - 20, '서는 자리', 13, '#fff',
                  'rgba(47,93,87,.88)', 가운데=True)]
    둘째 = None
    if 조류:
        둘째 = 조류.get('이름')
    elif 바닥:
        둘째 = 바닥.get('이름')
    elif 층:
        둘째 = 층.get('이름')
    else:
        # ★ 넷째 축 — 「끝자락」·「어초」처럼 **자리 자체**
        #   앞 셋이 안 걸리는 어종이 일곱이나 있었습니다.
        자리 = _고르기(어디, '자리')
        둘째 = 자리.get('이름') if 자리 else None
    if 둘째:
        라벨.append(_알약(min(max(노리x, 70), 560), 노리y - 14, 둘째, 13, '#fff',
                          'rgba(192,82,43,.88)', 가운데=True))

    # 바닥을 **색 띠**로도 보입니다 — 글자를 더 안 늘리면서
    바닥띠 = ''
    if 바닥:
        바닥띠 = ("<rect x='0' y='228' width='640' height='12'"
                  " fill='%s' opacity='.85'/>" % 바닥.get('색', 돌))

    출처 = 바탕.get('촬영자') or ''
    제목 = 바탕.get('제목') or ''
    꼬리 = ('사진 · %s · %s' % (제목, 출처)) if 출처 else ('사진 · %s' % 제목)

    return (
        '<figure class="cg-art cg-art--photo">\n'
        '<svg viewBox="0 0 640 240" role="img"'
        ' aria-label="%s 노리는 자리 그림" preserveAspectRatio="xMidYMid slice"'
        ' xmlns="http://www.w3.org/2000/svg">\n'
        '  <image href="%s" x="0" y="0" width="640" height="240"'
        ' preserveAspectRatio="%s slice"/>\n'
        '  <rect width="640" height="240" fill="url(#어둠)"/>\n'
        '  <defs><linearGradient id="어둠" x1="0" y1="0" x2="0" y2="1">'
        '<stop offset="0" stop-color="#000" stop-opacity=".14"/>'
        '<stop offset=".45" stop-color="#000" stop-opacity="0"/>'
        '<stop offset="1" stop-color="#000" stop-opacity=".46"/>'
        '</linearGradient></defs>\n'
        '  %s\n  %s\n  %s\n'
        '  %s\n  %s\n'
        '</svg>\n'
        '<figcaption>%s</figcaption>\n'
        '</figure>'
        % (조사(글(이름), '를'), html.escape(주소), 자르기,
           바닥띠, ''.join(꾸밈), ''.join(라벨),
           _알약(16, 32, '어디에 서서 노리나', 14, '#fff',
                 'rgba(0,0,0,.42)'),
           _알약(624 - 글자폭(꼬리, 11) - 20, 32, 꼬리, 11,
                 'rgba(255,255,255,.95)', 'rgba(0,0,0,.42)'),
           html.escape(꼬리)))


