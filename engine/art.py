#     실제 지형과 표시가 맞지 않습니다 — 방파제 사진 한 장에
#     붕장어의 「모래 바닥」을 찍는 식이었습니다.
#
#     바깥 검수도 인정했습니다 —
#       「실제 사진의 지형을 근거로 정확히 판독한 게 아니라면
#         **오히려 잘못된 정보를 확정적으로** 보여줍니다. 관광
