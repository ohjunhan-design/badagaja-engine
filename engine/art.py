        #   막대찌(200mm)가 5.25배가 되어 **그림 왼쪽 밖으로 86px 잘렸습니다.**
        #   주황 톱이 통째로 사라지고 회색 다리만 남아,
        #   「가늘고 긴 찌입니다」라고 적어 놓고 짧은 토막만 보였습니다.
        #   부품 쪽 카드(118×118)에서는 더 심했습니다.
