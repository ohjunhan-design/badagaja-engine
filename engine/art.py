    k = 처음
    몸 = ''
    for _ in range(12):
        몸 = _부품모양(이름, 폭 // 2, 높이 // 2, k)
        if not 몸:
            return ''
        if not 밖으로나간도형(몸, 폭, 높이, 여유):
            return 몸
        k *= 0.86
    return 몸


