    #   어종 안내가 가리키는 채비 이름이 rigs.json 에 실제로 있어야 합니다.
    print('[6] 어종이 가리키는 채비가 실제로 있는가 ★')
    안내길 = os.path.join(ROOT, 'data', 'raw', 'guide.json')
    안내 = io.read_json(안내길, default={}).get('어종') or []
    엉뚱 = []
    본것 = 0
    for 것 in 안내:
        # ★ **낚시 어종만 봅니다.** 해루질 대상의 `그림` 은 채비가 아니라
        #   생물 갈래(shell·crab·octopus…)를 가리킵니다 —
        #   맨손으로 잡는 데 채비가 있을 리 없습니다.
        if 것.get('갈래') != '낚시':
            continue
        갈 = 것.get('그림')
        if not 갈:
            continue
        본것 += 1
        if 갈 not in 채비:
            엉뚱.append('%s → %s' % ((것.get('이름') or {}).get('ko') or '?', 갈))
    if not 안내:
        print('  ~ 어종 안내 자료가 없습니다 — 잴 것이 없습니다')
    elif 엉뚱:
        막음.append('없는 채비를 가리키는 어종 %d가지' % len(엉뚱))
        print('  ✗ 없는 채비를 가리키는 어종 %d가지' % len(엉뚱))
        for x in 엉뚱:
            print('      %s' % x)
        print('      → 그 쪽에는 **채비도가 아예 안 나옵니다.**')
        print('        쓸 수 있는 이름: %s' % ' · '.join(sorted(채비)))
    else:
        print('  · 어종 %d가지가 모두 있는 채비를 가리킵니다' % 본것)
    print('')

    # ── [7] 그림이 **글씨 자리**를 덮지 않는가
    #
    #   ★ 2026-09-30 — 같은 잘못을 **네 번** 되풀이했습니다
    #     편대 · 웜 · 가지바늘 · 막대찌가 차례로 오른쪽으로 뻗어
    #     바로 옆의 이름과 호수를 덮었습니다.
    #     「목줄」이 반쯤 가려지고, 「웜  그럽웜 2~4인치」 위로
    #     꼬리가 올라앉았습니다.
    #
    #   채비도는 **왼쪽이 그림, 오른쪽이 글씨**입니다.
    #   글씨는 x=242 부터 적으므로, 그림이 그 앞(235)을 넘으면
    #   읽는 데 방해가 됩니다. 배경 사각형은 폭 전체라 뺍니다.
    print('[7] 그림이 글씨 자리를 덮지 않는가 ★')
    글씨왼쪽 = 235
    덮은것 = []
    본그림 = 0
    for 갈 in sorted(채비):
        쪽 = os.path.join(나온곳, url.rig(갈).replace('/', os.sep))
        if not os.path.isfile(쪽):
            continue
        글 = io.read(쪽, default='')
        m = re.search(r'<svg viewBox="0 0 \d+ \d+" role="img"'
                      r'[^>]*aria-label="[^"]*채비도".*?</svg>', 글, re.S)
        if not m:
            continue
        본그림 += 1
        쌓임 = [_그냥]
        for mm in re.finditer(_낱들, m.group(0)):
            조각 = mm.group(0)
            if 조각.startswith('<g'):
                g = re.search(r"transform=['\"]([^'\"]*)", 조각)
                바뀜 = _변환읽기(g.group(1)) if g else _그냥
                쌓임.append(_곱(쌓임[-1], 바뀜) if 바뀜 else 쌓임[-1])
                continue
            if 조각 == '</g>':
                if len(쌓임) > 1:
                    쌓임.pop()
                continue
            점 = _도형점들(조각)
            if not 점:
                continue
            점 = [_먹이기(쌓임[-1], a, b) for a, b in 점]
            좌 = min(q[0] for q in 점)
            우 = max(q[0] for q in 점)
            if 좌 < 10:
                continue                     # 배경 사각형
            if 우 > 글씨왼쪽 + 8:             # 8px 은 봐줍니다
                덮은것.append('%s — x=%d 까지 뻗음' % (갈, round(우)))
                break
    if 덮은것:
        막음.append('그림이 글씨를 덮는 채비 %d갈래' % len(덮은것))
        print('  ✗ 그림이 글씨 자리를 덮는 채비 %d갈래' % len(덮은것))
        for x in 덮은것:
            print('      %s' % x)
        print('      → 채비도는 **왼쪽이 그림, 오른쪽이 글씨**입니다.')
        print('        부품을 왼쪽으로 뻗게 하거나 크기를 줄이세요.')
    else:
        print('  · 채비도 %d장이 글씨 자리를 비워 둡니다' % 본그림)
    print('')

    # ── [8] 부품 **차례**의 근거가 있는가 ★
    #
    #   ★ 2026-09-30 — 주인이 물으셨습니다.
    #     「왜 이렇게 채비에 대한 그림이 자꾸 틀리는지 원인을 분석해서
    #       개선 방안을 찾아줘」
    #
    #   원인 — `부품` 배열의 **차례가 곧 위아래**인데, 자료를 만드는
    #     사람에게 그 약속이 보이지 않습니다. 글로 된 자료에는
    #     부품 이름만 있고 위아래가 없는 일이 많아, 결국 **짐작으로**
    #     차례를 정하게 됩니다. `art.py` 는 그 차례대로 그립니다.
    #
    #   실제로 여섯 번 틀렸습니다 —
    #     지그헤드 · 참돔(선상 채비) · 원투(편대로 그림) ·
    #     O형 고무 · 좁쌀봉돌 · 에기(봉돌 아래에 둠).
    #     **주인이 네 번 잡으셨습니다.** 검사기는 한 번도 못 잡았습니다.
    #
    #   그래서 **차례의 근거**(`차례근거`)를 적게 합니다.
    #   못 적으면 그 차례는 짐작입니다. 막지는 않되 늘 보여 줍니다.
    print('[8] 부품 차례의 근거가 적혀 있는가 \u2605')
    짐작 = []
    for _키, _것 in sorted(채비.items()):
        if not (_것.get('부품') or []):
            continue
        _근 = (_것.get('차례근거') or '').strip()
        if len(_근) < 20:
            짐작.append('%s (%s) — 부품 %d가지'
                        % (_키, _것.get('이름') or '', len(_것['부품'])))
    if 짐작:
        알림.append('차례 근거가 없는 채비 %d갈래' % len(짐작))
        print('  ! 부품 차례를 **짐작으로** 정한 채비 %d갈래' % len(짐작))
        for x in 짐작:
            print('      %s' % x)
        print('      \u2192 자료를 찾아 **위에서 아래 차례**를 확인하고')
        print('        `차례근거` 에 어디서 봤는지 적으세요.')
        print('        (글에 차례가 없으면 그것은 짐작입니다 \u2014')
        print('         짐작인 채로 두면 그림이 틀려도 아무도 모릅니다)')
    else:
        print('  \u00b7 채비 %d갈래가 모두 차례의 근거를 갖습니다'
              % len(채비))
    print('')

    if 알림:
        print('살펴볼 것 %d가지 (막지 않습니다)' % len(알림))
        for x in 알림:
            print('  ! %s' % x)
        print('')
    if 막음:
        print('손볼 곳 %d가지' % len(막음))
        for x in 막음:
            print('  ✗ %s' % x)
        return 1
    if 알림 and 엄격:
        return 2
    print('채비 %d가지가 모두 멀쩡합니다.' % len(채비))
    return 0


