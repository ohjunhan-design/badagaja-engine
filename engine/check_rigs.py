def 남의그림쓰나(채비):
    이름들 = []
    for 것 in 채비.values():
        for 한개 in (것.get('부품') or []):
            이름 = (한개.get('이름') or '').strip()
            if 이름 and 이름 not in 이름들:
                이름들.append(이름)
    탈 = []
    for i, ㄱ in enumerate(이름들):
        for ㄴ in 이름들[i + 1:]:
            if ㄱ == ㄴ:
                continue
            # 한쪽이 다른 쪽을 품고 있을 때만 봅니다
            if ㄱ not in ㄴ and ㄴ not in ㄱ:
                continue
            if (ㄱ, ㄴ) in 같아도되는짝 or (ㄴ, ㄱ) in 같아도되는짝:
                continue
            if art._부품모양(ㄱ, 100, 100) == art._부품모양(ㄴ, 100, 100):
                탈.append('「%s」와 「%s」가 같은 그림입니다' % (ㄱ, ㄴ))
    return 탈


def 조건차례():
    """`_부품모양()` 안의 `if '…' in 이름` 을 나온 차례대로 모읍니다."""
    글 = io.read(os.path.join(여기, 'art.py'), default='')
    m = re.search(r'def _부품모양\(.*?\n(.*?)\ndef ', 글, re.S)
    몸 = m.group(1) if m else ''
    차례 = []
    for mm in re.finditer(r"if '([^']+)' in 이름", 몸):
        차례.append(mm.group(1))
    return 차례


def 먼저나오나(차례, 좁은, 넓은):
    """좁은 이름이 넓은 이름보다 먼저 나오는가.

    둘 중 하나가 아예 없으면 **가로챌 일도 없으므로** 참입니다.
    """
    if 좁은 not in 차례 or 넓은 not in 차례:
        return True
    return 차례.index(좁은) < 차례.index(넓은)


