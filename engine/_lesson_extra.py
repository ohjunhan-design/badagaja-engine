def 미끼고르기(미끼글):
    """자료의 미끼 설명에서 **무엇을 쓰는지** 골라냅니다."""
    글 = 미끼글 or ''
    나옴 = []
    for 이름, 낱말들, 그리기, 귀띔 in 미끼그림:
        if any(w in 글 for w in 낱말들):
            나옴.append((이름, 그리기, 귀띔))
        if len(나옴) >= 3:
            break
    return 나옴


