def _간추림(글, 한도=150):
    """자료 글을 **그대로** 쓰되 너무 길면 문장 단위로 자릅니다."""
    글 = (글 or '').strip()
    if len(글) <= 한도:
        return 글
    자른 = 글[:한도]
    끝 = max(자른.rfind('. '), 자른.rfind('다.'))
    return (자른[:끝 + 2] if 끝 > 40 else 자른).strip()


