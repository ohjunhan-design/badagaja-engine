"""그림 수업 카드 **두 장**을 더 만듭니다 — 미끼 꿰는 법 · 언제 가나.

★ 2026-10-01 주인 지시
  「이것도 정보전달력이 전혀 없어 카드수량을 늘리더라도 더 많은
    정보가 필요해 어제 수집한 데이터를 기반으로 확장해봐
    다른 어종 및 해루질도 마찬가지야」
  「4칸이라 배치에 어색함이 있어 미끼주는 방법이나 계절별 날씨별
    아침 저녁별 미끼 선택방법이라던지 다른 더 많은 정보를
    2카드를 늘려서 배치에 어울리게 만들자」

  카드가 4장이면 2×2 로 끝나 허전합니다. **6장이면 2×3** 으로
  가지런하고, 그만큼 알려 줄 것도 늘어납니다.

★ **그림은 어종마다 새로 그리지 않습니다.**
  35가지 × 2장 = 70장을 손으로 그리면 한 장도 제대로 못 그립니다.
  미끼는 몇 종류로 모입니다 — 갯지렁이 11 · 크릴 8 · 새우 6 ·
  오징어살 4. 그 **종류별 그림**을 만들어 자료가 가리키는 대로
  골라 씁니다. 계절 띠도 마찬가지입니다.

★ **없는 말을 지어내지 않습니다.**
  자료(`미끼`·`언제`·`철`)에 있는 것만 씁니다.
  자료가 얇으면 그 카드는 **안 만듭니다** — 빈 제목만 남기느니
  없는 편이 낫습니다 (주인 지시 「이런정보 필요없어」).
"""
