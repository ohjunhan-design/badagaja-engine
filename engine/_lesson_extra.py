    #   그대로 두면 5장이 되어 2열 격자 마지막 줄에 한 장만
    #   남습니다 (주인 지시 ㉗ 「배치에 어울리게」).
    #   자리를 채우려고 아무거나 넣는 것이 아닙니다 —
    #   **「나도 할 수 있나」가 처음 하는 분의 첫 물음**입니다.
    #   그것이 안 풀리면 나머지를 안 읽습니다.
    #   ★ 처음에는 금어기 카드를 넣었다가 **바로 아래 「잡기 전에
    #     꼭 보세요」 칸과 똑같아져** 뺐습니다 (㉕ — 되풀이는
    #     성의 없어 보입니다).
