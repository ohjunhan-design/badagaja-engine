def _폭(글, 크기):
    """글 한 줄의 대략 폭(px). 한글은 크기만큼, 그 밖은 절반쯤."""
    return sum(크기 * (1.0 if ord(c) > 0x2000 else 0.55) for c in 글)


def _텍스트(x, y, 글, 크기=11, 굵기=700, 색=None, 가운데=False, 폭=None):
    """★ `폭` 을 주면 넘칠 때 **말줄임** 합니다 (2026-10-01)

    SVG <text> 는 저절로 줄바꿈도, 잘림도 없습니다. 자료가 길면
    viewBox 밖으로 끝없이 뻗고, 그러면 휴대폰에서 쪽 전체가
    가로로 넘칩니다 (주인 규칙 23 · check_render 가 잡았습니다).
    """
    if 폭 and _폭(글, 크기) > 폭:
        while len(글) > 1 and _폭(글 + '…', 크기) > 폭:
            글 = 글[:-1]
        글 = 글.rstrip() + '…'
    return ('<text x="%d" y="%d" font-size="%s" font-weight="%d" fill="%s"%s>'
            '%s</text>' % (x, y, 크기, 굵기, 색 or 풀,
                           ' text-anchor="middle"' if 가운데 else '', 글))


