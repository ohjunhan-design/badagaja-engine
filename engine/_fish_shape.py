# -*- coding: utf-8 -*-
"""물고기 한 마리를 **사실적으로** 그립니다.

★ 2026-09-30 주인 지적 — 「이런것들도 좀 사실적으로 그려
                          이건 유치원생 그림같잖아」

  옛 물고기는 **뾰족한 타원 + 삼각 꼬리 + 반달 선** 이 전부였습니다.
  입도 아가미도 가슴지느러미도 없었습니다.

  실제 물고기에 있는 것
    · 방추형 몸 — 머리 쪽이 굵고 꼬리자루로 갈수록 가늘어집니다
    · **갈라진 꼬리** — 뒤가 오목한 초승달꼴
    · 등지느러미 · 뒷지느러미 · 가슴지느러미
    · 아가미 뚜껑 선 · 입
    · 눈은 머리 앞쪽 위

  크기(a·b)와 색은 **원래 그림에서 읽어** 그대로 씁니다.
  그래야 다른 요소와 어긋나지 않습니다.

  ★ 첫 판에서 눈으로 잡은 것 (같은 날)
    · 등지느러미가 몸통에 묻혀 안 보였습니다 → 더 솟게
    · 가슴지느러미가 **배 밖으로** 삐져나왔습니다 → 몸 안쪽으로
    · 아가미 선이 **눈을 가로질렀습니다** → 눈을 앞으로, 선을 뒤로
"""


def _짙게(색, 몫=0.82):
    """색을 조금 어둡게 합니다 (지느러미를 몸과 갈라 보이게)."""
    색 = (색 or '').strip()
    if not (색.startswith('#') and len(색) == 7):
        return 색
    try:
        r, g, b = (int(색[i:i + 2], 16) for i in (1, 3, 5))
    except ValueError:
        return 색
    return '#%02x%02x%02x' % (int(r * 몫), int(g * 몫), int(b * 몫))


def 물고기(a, b, 몸색, 짙은색, 선색=None, 눈색='#223036'):
    """반폭 a · 반높이 b 인 물고기 한 마리를 냅니다 (머리는 오른쪽)."""
    지느색 = _짙게(짙은색, 0.92)
    선색 = 선색 or _짙게(짙은색, 0.72)
    굵기 = max(0.9, b * 0.10)

    def s(v):
        return ('%.1f' % v).rstrip('0').rstrip('.')

    조각 = []

    # ── 꼬리 — 뒤가 오목한 초승달꼴.
    #   몸통보다 **먼저** 그려 꼬리자루가 몸에 묻히게 합니다.
    조각.append(
        "<path d=\"M%s %s L%s %s Q%s 0 %s %s L%s %s Q%s 0 %s %sz\""
        " fill=\"%s\"/>" % (
            s(-a * 0.86), s(-b * 0.20),
            s(-a * 1.42), s(-b * 0.92),
            s(-a * 1.10),
            s(-a * 1.42), s(b * 0.92),
            s(-a * 0.86), s(b * 0.20),
            s(-a * 0.98),
            s(-a * 0.86), s(-b * 0.20),
            지느색))

    # ── 등지느러미 — 몸통 등선(-b)보다 **확실히 위로** 솟습니다
    조각.append(
        "<path d=\"M%s %s Q%s %s %s %s Q%s %s %s %sz\" fill=\"%s\"/>" % (
            s(a * 0.42), s(-b * 0.86),
            s(a * 0.10), s(-b * 1.92),
            s(-a * 0.26), s(-b * 0.92),
            s(a * 0.08), s(-b * 1.06),
            s(a * 0.42), s(-b * 0.86),
            지느색))

    # ── 뒷지느러미 — 배 쪽 뒤
    조각.append(
        "<path d=\"M%s %s Q%s %s %s %sz\" fill=\"%s\"/>" % (
            s(-a * 0.14), s(b * 0.80),
            s(-a * 0.40), s(b * 1.46),
            s(-a * 0.62), s(b * 0.52),
            지느색))

    # ── 몸통 — 방추형. 등이 솟고 꼬리자루로 가늘어집니다
    조각.append(
        "<path d=\"M%s 0"
        " C%s %s %s %s %s %s"
        " C%s %s %s %s %s %s"
        " L%s %s"
        " C%s %s %s %s %s %s"
        " C%s %s %s %s %s 0z\" fill=\"%s\"/>" % (
            s(a),
            s(a * 0.74), s(-b * 0.76), s(a * 0.16), s(-b * 1.02),
            s(-a * 0.42), s(-b * 0.72),
            s(-a * 0.70), s(-b * 0.54), s(-a * 0.82), s(-b * 0.32),
            s(-a * 0.88), s(-b * 0.19),
            s(-a * 0.88), s(b * 0.19),
            s(-a * 0.82), s(b * 0.32), s(-a * 0.70), s(b * 0.54),
            s(-a * 0.42), s(b * 0.72),
            s(a * 0.16), s(b * 1.02), s(a * 0.74), s(b * 0.76),
            s(a),
            몸색))

    # ── 가슴지느러미 — 아가미 바로 뒤, **몸 안쪽**에 눕습니다
    조각.append(
        "<path d=\"M%s %s Q%s %s %s %sz\" fill=\"%s\" opacity=\".8\"/>" % (
            s(a * 0.40), s(b * 0.08),
            s(a * 0.06), s(b * 0.58),
            s(a * 0.30), s(b * 0.60),
            선색))

    # ── 아가미 뚜껑 선 — 눈보다 **뒤쪽**입니다
    조각.append(
        "<path d=\"M%s %s Q%s 0 %s %s\" fill=\"none\" stroke=\"%s\""
        " stroke-width=\"%s\" opacity=\".4\"/>" % (
            s(a * 0.46), s(-b * 0.66),
            s(a * 0.30),
            s(a * 0.46), s(b * 0.66),
            선색, s(굵기)))

    # ── 입 — 머리 앞 짧은 선
    조각.append(
        "<path d=\"M%s %s L%s %s\" fill=\"none\" stroke=\"%s\""
        " stroke-width=\"%s\" stroke-linecap=\"round\" opacity=\".7\"/>" % (
            s(a * 0.96), s(-b * 0.02),
            s(a * 0.80), s(b * 0.12),
            선색, s(굵기)))

    # ── 눈 — 머리 앞쪽 위. 아가미 선보다 **앞**에 둡니다
    조각.append(
        "<circle cx=\"%s\" cy=\"%s\" r=\"%s\" fill=\"#f7f4ec\"/>"
        "<circle cx=\"%s\" cy=\"%s\" r=\"%s\" fill=\"%s\"/>" % (
            s(a * 0.72), s(-b * 0.32), s(max(1.7, b * 0.25)),
            s(a * 0.73), s(-b * 0.32), s(max(0.9, b * 0.13)), 눈색))

    return ''.join(조각)
