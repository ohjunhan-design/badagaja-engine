    var k = Math.floor((오늘 + 43200000 - 기준삭) / (삭망월 * 86400000));
    var 삭 = 삭시각(k);
    if (날시작(삭) > 오늘) 삭 = 삭시각(k - 1);
    if (날시작(삭시각(k + 1)) <= 오늘) 삭 = 삭시각(k + 1);
    return Math.round((오늘 - 날시작(삭)) / 86400000) + 1;
