/* 「다음 물때까지 얼마」 — **한 곳에서만 셉니다** (2026-10-08)
 *
 * ★ 왜 파일을 따로 두는가
 *   이 계산은 물때 지도(tide-map.js)가 하고 있었습니다. 포인트
 *   상세 패널에도 같은 줄이 필요해졌습니다. 복붙하면 **두 곳에서
 *   따로 셈하게 되고 반드시 어긋납니다** — 밤 11시에 한쪽은
 *   「내일 만조」라 적고 한쪽은 한 줄도 안 적는 식입니다.
 *   (기억 「숫자는 한 곳에서만」)
 *
 * ★ 지시 — 「물때 그래프는 새 계산 로직을 만들지 말고 기존
 *   renderer/data 를 재사용할 것」 (2026-10-08 바깥 검수)
 *   그래프는 BADAGAJA_TIDEGRAPH 가 그립니다. 이 파일은 그래프를
 *   그리지 않습니다 — **이미 있던 「다음까지」 계산을 옮겨 둔
 *   것뿐**입니다. 새로 만든 계산은 없습니다.
 *
 * ★ 없는 값을 만들지 않습니다.
 *   오늘 것이 다 지났고 내일치도 없으면 **빈 글자**입니다.
 */
(function () {
  'use strict';

  function 분으로(hm) {
    var p = String(hm || '').split(':');
    var h = parseInt(p[0], 10), m = parseInt(p[1], 10);
    if (isNaN(h) || isNaN(m)) { return null; }
    return h * 60 + m;
  }

  function 지금분() {
    var 이제 = new Date();
    return 이제.getHours() * 60 + 이제.getMinutes();
  }

  /* 아직 안 온 것 가운데 **가장 이른 것**. 없으면 null.
     오늘 것이 다 지났으면 내일 첫 것을 가리킵니다 — 밤에 보는
     사람이야말로 「다음에 언제 나갈까」를 묻습니다. */
  function 찾기(오늘들, 내일들) {
    var 이제 = 지금분();
    var 것들 = 오늘들 || [];
    for (var i = 0; i < 것들.length; i++) {
      var 분 = 분으로(것들[i].time);
      if (분 !== null && 분 > 이제) {
        return { 때: 것들[i], 남은분: 분 - 이제, 내일: false };
      }
    }
    var 내 = (내일들 || [])[0];
    if (내) {
      var 분2 = 분으로(내.time);
      if (분2 !== null) {
        return { 때: 내, 남은분: (24 * 60 - 이제) + 분2, 내일: true };
      }
    }
    return null;
  }

  function 얼마(남은분) {
    var 시 = Math.floor(남은분 / 60), 밈 = 남은분 % 60;
    return (시 ? 시 + '시간 ' : '') + 밈 + '분';
  }

  /* 사람이 읽는 한 줄. 가리킬 것이 없으면 **빈 글자**입니다 */
  function 글(오늘들, 내일들) {
    var 것 = 찾기(오늘들, 내일들);
    if (!것) { return ''; }
    if (것.내일) {
      return '내일 ' + 것.때.type + ' ' + 것.때.time
           + ' · ' + 얼마(것.남은분) + ' 뒤';
    }
    return '다음 ' + 것.때.type + '까지 ' + 얼마(것.남은분);
  }

  window.BADAGAJA_TIDENEXT = {
    찾기: 찾기, 글: 글, 분으로: 분으로, 얼마: 얼마
  };
})();
