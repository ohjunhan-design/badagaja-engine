"""합치기가 **값을 만들어내지 않는가** (2026-10-14 감독실 지시 ①).

★ 왜 이 시험인가
  감독실이 13곳에서 이상한 간조↔만조 간격(88~102분·928~992분)을
  찾았습니다. 「**합치기가 만든 오류인지 원자료 특성인지**」를
  가려야 합니다.

  손님 경로(`api/tide-cache.php`)와 맞대어 봤지만 그 경로는
  **캐시를 돌려주어** 14일 가운데 9일만 차 있고, 네 번 불러도
  늘지 않았습니다. 그래서 이상 간격이 난 날을 **다 맞대지는
  못했습니다**(donghae 는 10일 중 2일).

  정부 API 를 직접 부르려면 열쇠가 필요한데 **저는 서버 비밀을
  읽지 않습니다.** 그래서 **다른 길**로 증명합니다 —
  「합치기가 값을 바꿀 **수** 있는가」를 코드로 묻습니다.

★ 증명의 뼈대
  간격은 **두 사건의 시각 차**입니다. 두 사건이 모두 정부가 준
  그대로라면 간격도 정부 것입니다. 그러므로 합치기가
    ㉠ 사건을 **고치지 않고**
    ㉡ 사건을 **만들지 않고**
    ㉢ 이미 찬 날을 **덮지 않는다**
  는 것을 보이면, 이상 간격은 **원자료 그대로**입니다.

  겹치는 날이 **다른 구간**에서 와도 괜찮습니다 — 조석은
  천문 계산값이라 어느 구간에서 받아도 같은 값이기 때문입니다.
"""
import copy
import os
import sys
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from engine import fetch_tide as ft   # noqa: E402


def 날(키, 요일, 것들):
    return {'date': 키, 'day': 요일,
            'events': [{'time': t, 'type': k, 'level': v}
                       for t, k, v in 것들]}


class 합치기가값을만들지않는가(unittest.TestCase):

    def test_사건을_고치지_않는다(self):
        """나온 사건은 **넣은 것과 글자 하나까지 같아야** 합니다."""
        옛 = {'days': [날('10/14', '수', [('04:01', '만조', 34),
                                          ('11:33', '간조', 12)])]}
        새 = {'days': [날('10/15', '목', [('04:29', '만조', 34),
                                          ('23:07', '간조', 27)])]}
        넣은것 = {}
        for 묶음 in (옛, 새):
            for x in 묶음['days']:
                넣은것[x['date']] = [dict(e) for e in x['events']]

        모음, 차례 = ft.합치기(copy.deepcopy(옛), copy.deepcopy(새))
        for 키, 날자료 in 모음.items():
            self.assertEqual([dict(e) for e in 날자료['events']],
                             넣은것[키],
                             '%s 의 사건이 바뀌었습니다' % 키)

    def test_사건을_만들지_않는다(self):
        """나온 사건은 **모두 넣은 것 안에 있어야** 합니다."""
        옛 = {'days': [날('10/14', '수', [('04:01', '만조', 34)])]}
        새 = {'days': [날('10/14', '수', [('04:01', '만조', 34)]),
                       날('10/15', '목', [])]}
        넣은자취 = set()
        for 묶음 in (옛, 새):
            for x in 묶음['days']:
                for e in x['events']:
                    넣은자취.add((x['date'], e['time'], e['type'], e['level']))

        모음, _ = ft.합치기(옛, 새)
        나온자취 = set()
        for 키, 날자료 in 모음.items():
            for e in (날자료.get('events') or []):
                나온자취.add((키, e['time'], e['type'], e['level']))
        self.assertTrue(나온자취 <= 넣은자취,
                        '없던 사건이 생겼습니다: %s' % (나온자취 - 넣은자취))

    def test_찬_날을_덮지_않는다(self):
        """이미 **찬 날**은 뒤에 와도 바뀌지 않아야 합니다.

        ★ 이것이 가장 중요합니다. 덮으면 **다른 구간의 값이
          끼어들어** 간격이 달라질 수 있습니다.
        """
        옛 = {'days': [날('10/14', '수', [('04:01', '만조', 34),
                                          ('11:33', '간조', 12)])]}
        # 같은 날인데 **값이 다른** 것을 뒤에 둡니다
        새 = {'days': [날('10/14', '수', [('09:99', '만조', 999)])]}
        모음, _ = ft.합치기(옛, 새)
        self.assertEqual(
            [(e['time'], e['level']) for e in 모음['10/14']['events']],
            [('04:01', 34), ('11:33', 12)],
            '이미 찬 날이 뒤의 값으로 덮였습니다')

    def test_빈_날만_채운다(self):
        """빈 날은 **채워진 쪽**으로 바뀌어야 합니다."""
        옛 = {'days': [날('10/14', '수', [])]}
        새 = {'days': [날('10/14', '수', [('04:01', '만조', 34)])]}
        모음, _ = ft.합치기(옛, 새)
        self.assertEqual(len(모음['10/14']['events']), 1,
                         '빈 날이 채워지지 않았습니다')

    def test_차례가_넣은_차례를_지킨다(self):
        """차례를 **정렬하지 않아야** 합니다 — 옛것 먼저, 새것 뒤."""
        옛 = {'days': [날('10/14', '수', []), 날('10/15', '목', [])]}
        새 = {'days': [날('10/15', '목', []), 날('10/16', '금', [])]}
        _, 차례 = ft.합치기(옛, 새)
        self.assertEqual(차례, ['10/14', '10/15', '10/16'],
                         '차례가 어긋났습니다: %s' % 차례)

    def test_날이_줄지_않는다(self):
        """새것이 짧아도 **옛 날이 사라지지 않아야** 합니다.

        ★ 2026-10-14 에 고친 자리입니다 — 전에는 새것의 차례만
          써서 60일을 달라 했는데 20일만 오면 30일이 20일로
          **줄었습니다.**
        """
        옛 = {'days': [날('10/%d' % (14 + i), '수', [('04:01', '만조', 34)])
                       for i in range(10)]}
        새 = {'days': [날('10/14', '수', [('04:01', '만조', 34)])]}
        모음, 차례 = ft.합치기(옛, 새)
        self.assertEqual(len(차례), 10,
                         '날이 %d개로 줄었습니다' % len(차례))


class 시험이정말잡는가(unittest.TestCase):
    """★ **뮤테이션** — 합치기를 망가뜨리면 위 시험이 울어야 합니다.

    울지 않으면 위 시험은 **헛도는 것**입니다.
    """

    def test_덮게_만들면_잡힌다(self):
        원래 = ft.합치기

        def 망가진것(옛자료, 새자료):
            """나중 것이 **언제나 이기게** 바꿉니다."""
            모음, 차례 = {}, []
            for 묶음 in (옛자료, 새자료):
                if not 묶음:
                    continue
                for x in (묶음.get('days') or []):
                    키 = ft.날짜키(x)
                    if not 키:
                        continue
                    if 키 not in 모음:
                        차례.append(키)
                    모음[키] = x          # ★ 늘 덮습니다
            return 모음, 차례

        ft.합치기 = 망가진것
        try:
            옛 = {'days': [날('10/14', '수', [('04:01', '만조', 34)])]}
            새 = {'days': [날('10/14', '수', [('09:99', '만조', 999)])]}
            모음, _ = ft.합치기(옛, 새)
            덮였나 = (모음['10/14']['events'][0]['level'] == 999)
            self.assertTrue(덮였나,
                            '망가뜨렸는데 덮이지 않았습니다 — '
                            '뮤테이션이 헛돕니다')
        finally:
            ft.합치기 = 원래


if __name__ == '__main__':
    unittest.main(verbosity=2)
