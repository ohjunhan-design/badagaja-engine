# -*- coding: utf-8 -*-
"""핀이 **엉뚱한 곳에 찍혔는지** 다시 볼 곳을 차례대로 냅니다 (2026-10-08).

★ ★ 이것이 무엇인지 — 주인이 바로잡아 주셨습니다 ★ ★

      「포인트의 특성상 **정확한 좌표는 불가능해**. … 모든 포인트를
        정확히 할 수 없기에 **사람들도 이 부분을 인정을 하는 거야.**
        그래서 **위성지도로 확인을 다시 하고 포인트에 진입을 하는
        거고.」

  그래서 이 큐는 「틀린 좌표 목록」이 아닙니다. **엉뚱한 내륙·다른
  섬·다른 지역에 찍힌 핀**을 사람이 빨리 찾도록 **차례를 정해 줄
  뿐**입니다.

★ **고치지 않습니다.** 짐작해 좌표를 당기면 틀린 좌표를 그럴듯한
  다른 틀린 좌표로 바꿉니다. 최종 판단은 위성지도에서 해안 모양과
  들어갈 수 있는지를 **사람 눈으로** 보고 정합니다.

★ 판정은 **`engine/check_coast.py` 가 낸 것만** 읽습니다.
  전에는 여기서 거리를 다시 쟀는데, 검사기가 하는 「자료가 안 닿는
  권역 걸러내기」를 안 거쳐 **서해5도·제주가 「해안형 3km 초과」로
  끼었습니다.** 두 곳에서 따로 셈하면 반드시 어긋납니다.
  (기억 「숫자는 한 곳에서만」)
"""
import io as _io
import json
import os
import sys
import urllib.parse

여기 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, 여기)
sys.stdout.reconfigure(encoding='utf-8', errors='replace')

from engine import check_coast as C   # noqa: E402

낼곳 = os.path.join(여기, 'data-private', '좌표-다시볼곳.md')


def main():
    판정길 = os.path.join(여기, 'tests', 'out', '좌표판정.json')
    if not os.path.isfile(판정길):
        print('□ 판정이 없습니다 — 먼저 engine/check_coast.py 를 돌리세요')
        return 1
    판정 = json.loads(_io.open(판정길, encoding='utf-8').read())
    상태 = 판정.get('상태') or {}
    지명이상 = 판정.get('지명이상') or {}
    문턱 = 판정.get('문턱') or {}
    검토선 = 문턱.get('검토선', 1.0)
    경고선 = 문턱.get('경고선', 3.0)

    것들 = C.포인트들()
    표 = dict((x.get('id'), x) for x in 것들)
    무리좌표 = {}
    for (권역, 앞), 들 in C.지명묶기(것들).items():
        for y in 들:
            if y.get('id') in 지명이상:
                무리좌표[y['id']] = [
                    ((z.get('이름') or {}).get('ko'),
                     (z.get('좌표') or {}).get('위도'),
                     (z.get('좌표') or {}).get('경도'))
                    for z in 들 if z.get('id') != y.get('id')][:4]

    def 점수(아이디):
        """위험도 — 바깥 검수가 준 점수표 그대로입니다.

            +5 해안형인데 3km 초과
            +4 같은 지명 무리에서 혼자 8km 넘게 떨어짐
            +2 해안형인데 1km 초과
            +1 좌표는 있으나 자료가 안 닿아 못 잼

        7점 이상 → 즉시 보기 · 4~6 → 2차 · 1~3 → 후순위
        """
        x = 표.get(아이디) or {}
        해안, 예외 = C.지형갈래(x.get('지형'))
        km = (상태.get(아이디) or {}).get('바다까지')
        p = 0
        if 해안 and not 예외 and km is not None:
            if km > 경고선:
                p += 5
            elif km > 검토선:
                p += 2
        if 아이디 in 지명이상:
            p += 4
        if km is None:
            p += 1
        return p

    # ★ 검사기가 REVIEW·FAIL 이라 한 것만 봅니다.
    #   APPROX(1~3km)는 대표 진입점일 수 있어 **어김이 아닙니다.**
    후보 = [k for k, v in 상태.items()
            if v.get('상태') in ('REVIEW', 'FAIL')]

    줄 = ['# 핀이 엉뚱한 곳에 찍혔는지 다시 볼 곳', '',
          '> **이것은 정확한 낚시점 GPS 검증이 아닙니다.**',
          '> 포인트 좌표는 흔히 **대표 진입점**입니다 — 포구 입구,',
          '> 방파제 시작점, 진입 도로, 갯바위 배후 주차장.',
          '> 몇백 미터 어긋나는 것은 잘못이 아니라 이 자료의 성질이고,',
          '> 손님은 **위성지도로 해안 모양과 들어가는 길을 보고**',
          '> 최종 판단합니다. (2026-10-08 주인 지시)',
          '',
          '## 사람이 볼 때 이 넷만 보면 됩니다',
          '',
          '1. 포인트 이름·지역명이 이 주변과 맞는가',
          '2. 해안·방파제·갯바위·선착장이 실제로 보이는가',
          '3. 차나 도보로 들어갈 수 있는 대표 지점을 가리키는가',
          '4. 정확한 자리까지는 아니어도 손님이 위성지도로 판단 가능한가',
          '',
          '1~3 이 맞으면 핀이 몇백 미터 어긋나도 **그냥 둡니다.**',
          '',
          '**고치지 않았습니다** — 짐작해 당기면 틀린 좌표를 그럴듯한',
          '다른 틀린 좌표로 바꿉니다. 고친 뒤에는',
          '`tests/golden/좌표.json` 에서 그 id 를 지우세요. 그래야',
          '같은 일이 다시 생길 때 배포가 막힙니다.',
          '',
          '모두 **%d곳**입니다.' % len(후보), '',
          '## 보고 나서 세 가지로만 적습니다',
          '',
          '바깥 검수가 정한 방식입니다 — 「정상 / 수정필요 / 애매',
          '세 가지만 기록하고, 20곳 결과를 본 뒤 지명 규칙을',
          '보강하세요. 실제 사람이 내린 20개의 판정이 검사기',
          '학습자료 역할을 합니다」',
          '',
          '| 적을 말 | 뜻 | 그 다음 |',
          '|---|---|---|',
          '| **정상** | 핀이 그 자리를 가리키고 있습니다 |'
          ' `tests/golden/좌표.json` 의 `괜찮음` 에 **지금 좌표와**'
          ' 함께 적습니다. 좌표가 나중에 바뀌면 승인이 저절로'
          ' 거둬집니다 |',
          '| **수정필요** | 다른 곳을 가리킵니다 |'
          ' **근거 있는 좌표만** 고칩니다. 짐작해 당기지 않습니다 |',
          '| **애매** | 위성으로도 모르겠습니다 |'
          ' 그대로 둡니다. 다음에 다시 봅니다 |',
          '',
          '## 7점 이상 — 즉시 보기', '']

    앞선것 = sorted(
        후보,
        key=lambda k: (-점수(k),
                       -((상태.get(k) or {}).get('바다까지') or 0)))
    머리낸것 = {'가운데': False, '낮음': False}
    for 아이디 in 앞선것:
        p = 점수(아이디)
        if 4 <= p <= 6 and not 머리낸것['가운데']:
            머리낸것['가운데'] = True
            줄 += ['', '## 4~6점 — 2차로 보기', '']
        if p <= 3 and not 머리낸것['낮음']:
            머리낸것['낮음'] = True
            줄 += ['', '## 1~3점 — 후순위', '']
        x = 표.get(아이디) or {}
        좌 = x.get('좌표') or {}
        이름 = (x.get('이름') or {}).get('ko') or ''
        km = (상태.get(아이디) or {}).get('바다까지')
        줄.append('- **%s** · %s · `%s` · **%d점**'
                  % (이름, x.get('지형') or '', 아이디, p))
        줄.append('  - 지금 좌표 `%s, %s` · 권역 `%s`'
                  % (좌.get('위도'), 좌.get('경도'), x.get('권역')))
        # ★ **눌러서 바로 볼 수 있게 지도 주소를 답니다** (2026-10-08)
        #   목록만 주면 좌표를 손으로 옮겨 적어야 합니다. 20곳이면
        #   그것만으로도 지칩니다. 바깥 검수 —
        #     「20곳은 사람이 위성지도로 한 번씩 확인하는 게 가장
        #       싸고 정확합니다」
        #   싸게 하려면 **누르면 바로 그 자리가 떠야** 합니다.
        #   정부·공공기관만 연결하는 규칙(12)은 **사이트에 내는 링크**
        #   이야기이고, 이 파일은 data-private 이라 웹에 안 나갑니다.
        if 좌.get('위도') is not None:
            # 빈칸이 든 이름을 그대로 넣으면 마크다운 링크가 거기서
            # 끊깁니다. 주소에 쓸 수 있게 옮겨 적습니다.
            깨끗한이름 = urllib.parse.quote(
                (이름 or '포인트').replace(',', ' '), safe='')
            줄.append('  - 위성으로 보기 — '
                      '[카카오맵](https://map.kakao.com/link/map/'
                      '%s,%s,%s)'
                      % (깨끗한이름, 좌.get('위도'), 좌.get('경도')))
        if km is not None:
            줄.append('  - 바다까지 **%.2fkm**' % km)
        if 아이디 in 지명이상:
            g = 지명이상[아이디]
            줄.append('  - 「%s」 무리 %d곳에서 **혼자 %.1fkm 떨어져'
                      ' 있습니다** (가장 가까운 동료까지)'
                      % (g['앞낱말'], g['무리크기'], g['혼자떨어짐']))
            for 이, a, b in 무리좌표.get(아이디, []):
                줄.append('    - 같은 무리: %s `%s, %s`' % (이, a, b))

    줄 += ['', '---', '',
           '※ 이 파일은 `data-private/` 에 있습니다 — 웹에 안 냅니다'
           ' (주인 규칙 11).']

    os.makedirs(os.path.dirname(낼곳), exist_ok=True)
    _io.open(낼곳, 'w', encoding='utf-8').write(chr(10).join(줄))
    print('  · 다시 볼 곳 %d곳을 적었습니다' % len(후보))
    print('  · %s' % os.path.relpath(낼곳, 여기))
    return 0


if __name__ == '__main__':
    sys.exit(main())
