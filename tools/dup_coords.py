# -*- coding: utf-8 -*-
"""서로 다른 곳이 **같은 좌표**를 쓰는 묶음을 가립니다 (2026-10-08).

★ 왜 묶음 단위인가 — 바깥 검수가 바로잡았습니다

      「693곳을 전부 다시 찍으려 하지 마세요. **포인트 단위가
        아니라 『같은 좌표 묶음』 단위로 관리**해야 합니다.
        693개보다 묶음 수가 훨씬 적습니다.
        … 지금은 693곳을 정확하게 고치는 프로젝트가 아니라,
        **693곳에서 거짓 정확함을 제거하는 프로젝트**로
        접근하는 게 맞습니다」

  포인트 693곳이지만 묶음은 297개입니다. 묶음 하나를 보면
  그 안의 여러 곳이 한꺼번에 정리됩니다.

★ 세 갈래로만 가립니다 (바깥 검수가 정한 분류)

    같은자리    같은 항·방파제 둘레를 낚시/해루질/지형만 달리 적음
                → 좌표가 같아도 **말이 됩니다.** 후순위.
    대표좌표    서로 다른 소분류인데 권역 대표 좌표를 임시로 넣음
    명백한오류  북측/남측, 서로 다른 마을·해변·방파제처럼
                **같은 좌표일 수 없는** 것. 먼저 봅니다.

★ **좌표를 고치지 않습니다.** 가리기만 합니다.
  바깥 검수 — 「자동으로 좌표를 고치지는 말고, 이 세 분류만
  먼저 하세요」

쓰는 법
    python tools/dup_coords.py            # 표를 냅니다
    python tools/dup_coords.py --적기     # data-private 에 적습니다
"""
import io
import json
import os
import re
import sys
import glob
import collections

여기 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, 여기)
sys.stdout.reconfigure(encoding='utf-8', errors='replace')

자료길 = os.path.join(여기, 'data', 'raw', 'points')
낼곳 = os.path.join(여기, 'data-private', '좌표-겹친묶음.md')

# ★ **같은 좌표일 수 없는 표시** — 이름에 이것이 서로 다르게 들어가면
#   그 둘은 다른 자리입니다. 북측과 남측이 한 점일 수 없습니다.
방위 = ('북측', '남측', '동측', '서측', '북단', '남단', '동단', '서단',
        '북쪽', '남쪽', '동쪽', '서쪽', '좌측', '우측', '윗', '아래',
        '뒷', '앞', '안쪽', '바깥')

# ★ **같은 항 둘레의 여러 모습** — 이것만 다르면 같은 자리일 수 있습니다
#   (한 항구에 방파제도 있고 선착장도 있고 갯바위도 있습니다)
생김새 = ('방파제', '선착장', '갯바위', '해변', '갯벌', '조간대', '항',
          '포구', '제방', '방조제', '테트라', '등대', '해안', '암반',
          '모래', '여', '권', '일대', '주변', '부근', '인근', '입구')


def 알맹이(이름):
    """이름에서 **생김새·방위를 뺀 알맹이**만 남깁니다.

    「청산도 권덕항 방파제」 → 「청산도 권덕」
    「청산도 코바위」        → 「청산도 코」
    둘의 알맹이가 다르면 **다른 자리**입니다.
    """
    글 = 이름 or ''
    for 낱말 in 방위 + 생김새:
        글 = 글.replace(낱말, ' ')
    글 = re.sub(r'[()·,~\-]+', ' ', 글)
    return ' '.join(글.split())


def 방위쓰임(이름):
    return set(x for x in 방위 if x in (이름 or ''))


def 가리기(들):
    """묶음 하나를 세 갈래 가운데 하나로 가립니다.

    돌려주는 것 — (갈래, 까닭)
    """
    이름들 = [x['이름'] for x in 들]
    알맹이들 = set(알맹이(n) for n in 이름들)

    # ① 방위가 서로 다르게 붙어 있으면 **같은 좌표일 수 없습니다**
    방위들 = [방위쓰임(n) for n in 이름들]
    쓰인방위 = set()
    for s in 방위들:
        쓰인방위 |= s
    if len(쓰인방위) >= 2:
        return '명백한오류', '방위가 서로 다릅니다 (%s)' % ', '.join(
            sorted(쓰인방위))

    # ② 알맹이가 여럿이면 **서로 다른 마을·섬·바위**입니다
    #
    #   ★ 다만 **포함 관계는 뺍니다** — 「개도」·「개도 모전리」·
    #     「개도 모전리 마을」은 점점 좁혀 적은 것이지 다른 곳이
    #     아닙니다. 반면 「청산도 덕」과 「청산도 도락리」는 섬 안의
    #     서로 다른 마을이라 한 점일 수 없습니다.
    다른쌍 = []
    차례대로 = sorted(알맹이들)
    for i in range(len(차례대로)):
        for j in range(i + 1, len(차례대로)):
            a, b = 차례대로[i], 차례대로[j]
            if a.startswith(b) or b.startswith(a):
                continue          # 좁혀 적은 것입니다
            다른쌍.append((a, b))
    if 다른쌍:
        a, b = 다른쌍[0]
        return '명백한오류', '다른 자리입니다 (%s / %s)' % (a, b)

    # ③ 다섯 곳 넘게 한 점에 몰리면 대표 좌표를 넣은 자리입니다
    if len(들) >= 5:
        return '대표좌표', '%d곳이 한 점에 몰려 있습니다' % len(들)

    # ④ 알맹이가 하나고 생김새만 다르면 **같은 자리일 수 있습니다**
    if len(알맹이들) == 1:
        갈래들 = set(x.get('갈래') or '' for x in 들)
        if len(갈래들) >= 2:
            return '같은자리', '같은 곳을 낚시·해루질로 나눠 적었습니다'
        return '같은자리', '같은 곳의 다른 생김새입니다'

    return '대표좌표', '가리기 어렵습니다'


def 모으기():
    자리표 = collections.defaultdict(list)
    for f in sorted(glob.glob(os.path.join(자료길, '*.json'))):
        d = json.loads(io.open(f, encoding='utf-8').read())
        for x in (d.get('포인트') or d.get('points') or []):
            좌 = x.get('좌표') or {}
            if 좌.get('위도') is None:
                continue
            키 = (round(좌['위도'], 6), round(좌['경도'], 6))
            이름 = x.get('이름')
            if isinstance(이름, dict):
                이름 = 이름.get('ko') or ''
            자리표[키].append({
                'id': x.get('id'), '이름': 이름 or '',
                '권역': x.get('권역'), '갈래': x.get('갈래'),
                '지형': x.get('지형'),
            })
    return {k: v for k, v in 자리표.items() if len(v) > 1}


def main():
    겹침 = 모으기()
    묶음 = []
    for (la, lo), 들 in 겹침.items():
        갈래, 까닭 = 가리기(들)
        묶음.append({'위도': la, '경도': lo, '곳수': len(들),
                     '갈래': 갈래, '까닭': 까닭, '것들': 들})
    # ★ 차례를 정해 둡니다 — 돌릴 때마다 달라지면 못 견줍니다
    차례 = {'명백한오류': 0, '대표좌표': 1, '같은자리': 2}
    묶음.sort(key=lambda m: (차례[m['갈래']], -m['곳수'],
                             m['위도'], m['경도']))

    셈 = collections.Counter(m['갈래'] for m in 묶음)
    곳셈 = collections.Counter()
    for m in 묶음:
        곳셈[m['갈래']] += m['곳수']

    print('서로 다른 곳이 같은 좌표를 쓰는 묶음')
    print('')
    print('  묶음 %d개 · 포인트 %d곳'
          % (len(묶음), sum(m['곳수'] for m in 묶음)))
    print('')
    for 갈래 in ('명백한오류', '대표좌표', '같은자리'):
        print('  %-10s 묶음 %3d개 · %4d곳'
              % (갈래, 셈[갈래], 곳셈[갈래]))
    print('')
    print('  먼저 볼 것 — 「명백한오류」 묶음 가운데 큰 쪽 10개')
    for m in [x for x in 묶음 if x['갈래'] == '명백한오류'][:10]:
        print('   ! %.6f, %.6f · %d곳 · %s'
              % (m['위도'], m['경도'], m['곳수'], m['까닭']))
        for x in m['것들'][:3]:
            print('       %-10s %s' % (x['권역'], x['이름']))

    if '--적기' in sys.argv:
        줄 = ['# 서로 다른 곳이 같은 좌표를 쓰는 묶음', '',
              '> 바깥 검수 — 「693곳을 전부 다시 찍으려 하지 마세요.',
              '> **포인트 단위가 아니라 「같은 좌표 묶음」 단위로**',
              '> 관리해야 합니다. … 지금은 693곳을 정확하게 고치는',
              '> 프로젝트가 아니라, **693곳에서 거짓 정확함을 제거하는**',
              '> 프로젝트로 접근하는 게 맞습니다」', '',
              '**좌표를 고치지 않았습니다.** 가리기만 했습니다.', '',
              '| 갈래 | 묶음 | 곳 | 무엇인가 |', '|---|---|---|---|',
              '| 명백한오류 | %d | %d | 북측/남측처럼 **같은 좌표일 수'
              ' 없는** 것. 먼저 봅니다 |'
              % (셈['명백한오류'], 곳셈['명백한오류']),
              '| 대표좌표 | %d | %d | 권역 대표 좌표를 임시로 넣은 것 |'
              % (셈['대표좌표'], 곳셈['대표좌표']),
              '| 같은자리 | %d | %d | 같은 항 둘레를 생김새·갈래만 달리'
              ' 적은 것. 후순위 |'
              % (셈['같은자리'], 곳셈['같은자리']), '']
        for 갈래 in ('명백한오류', '대표좌표', '같은자리'):
            줄 += ['', '## %s' % 갈래, '']
            for m in [x for x in 묶음 if x['갈래'] == 갈래]:
                줄.append('- `%.6f, %.6f` · **%d곳** — %s'
                          % (m['위도'], m['경도'], m['곳수'], m['까닭']))
                줄.append('  - 위성으로 보기 — '
                          '[카카오맵](https://map.kakao.com/link/map/'
                          '%s,%s,%s)'
                          % (m['것들'][0]['이름'].replace(',', ' ')
                             .replace(' ', '%20'), m['위도'], m['경도']))
                for x in m['것들']:
                    줄.append('  - %s · `%s` · %s'
                              % (x['이름'], x['id'], x['지형'] or ''))
        os.makedirs(os.path.dirname(낼곳), exist_ok=True)
        io.open(낼곳, 'w', encoding='utf-8').write('\n'.join(줄) + '\n')
        print('')
        print('  · %s 에 적었습니다' % os.path.relpath(낼곳, 여기))
    return 0


if __name__ == '__main__':
    sys.exit(main())
